//! HEQK secure-boot signer (host tool). Hybrid: classical ed25519 AND
//! post-quantum SLH-DSA (FIPS 205, SHA2-128s). The boot manager requires BOTH
//! signatures to verify — breaking secure boot requires breaking BOTH schemes.
//!
//!   heqk-sign keygen <keydir>            -> secret keys + printable pubkeys
//!   heqk-sign sign   <keydir> <payload> <ed25519.sig> <slhdsa.sig>
//!
//! Both signatures are over the 32-byte SHA-256 of the payload (the same
//! measurement HBoot recomputes and binds the verification to).

use ed25519_compact::{KeyPair, Noise, PublicKey, SecretKey, Signature};
use fips205::slh_dsa_sha2_128f; // AK (fast on-device sign)
use fips205::slh_dsa_sha2_128s; // boot signatures (verify-only on device)
use fips205::traits::{SerDes, Signer, Verifier};
use sha2::{Digest, Sha256};
use std::fs;

const CTX: &[u8] = b"HEQK-BOOT-v1";
const AK_CTX: &[u8] = b"HEQK-ATTEST-v1";
/// The verifier's challenge nonce (in a real deployment this is fresh per
/// request over a channel; fixed here so the on-device quote is checkable).
const CHALLENGE_NONCE: [u8; 32] = *b"HEQK-attestation-demo-nonce-0001";
const NUM_PCR: usize = 4;

/// Generate the device Attestation Key (hybrid ed25519 + SLH-DSA). Writes the
/// AK secret keys + an attest_keys.rs for HBoot to embed (software AK — a
/// hardware-bound AK from OTP is the follow-on).
fn akgen(keydir: &str) {
    fs::create_dir_all(keydir).unwrap();
    let ed = KeyPair::generate();
    fs::write(format!("{keydir}/ak_ed.sk"), ed.sk.as_ref()).unwrap();
    fs::write(format!("{keydir}/ak_ed.pk"), ed.pk.as_ref()).unwrap();
    let (pq_pk, pq_sk) = slh_dsa_sha2_128f::try_keygen().expect("ak slh keygen");
    let pq_sk_bytes = pq_sk.into_bytes();
    fs::write(format!("{keydir}/ak_slh.sk"), pq_sk_bytes).unwrap();
    fs::write(format!("{keydir}/ak_slh.pk"), pq_pk.into_bytes()).unwrap();

    let mut src = String::new();
    src.push_str("// GENERATED by heqk-sign akgen — HBoot's embedded Attestation Key.\n");
    src.push_str("// SOFTWARE AK: the private key lives in the HBoot binary. A hardware-\n");
    src.push_str("// bound AK (derived from BCM2712 OTP) is the follow-on that anchors it.\n\n");
    src.push_str(&rust_array("AK_ED25519_SK", ed.sk.as_ref()));
    src.push_str(&rust_array("AK_SLHDSA_SK", &pq_sk_bytes));
    fs::write(format!("{keydir}/attest_keys.rs"), src).unwrap();
    println!("akgen: wrote AK (ed25519+SLH-DSA) to {keydir}; attest_keys.rs ready to embed");
}

/// Verify a device-emitted attestation quote (extracted from serial). File
/// layout: nonce(32) || svn(8 LE) || PCR0..3(128) || ed_sig(64) || slh_sig(7856).
fn quote_verify(keydir: &str, quote_file: &str) {
    let q = fs::read(quote_file).expect("read quote");
    let body_len = 32 + 8 + 32 * NUM_PCR;
    let ed_len = 64;
    let expect = body_len + ed_len + slh_dsa_sha2_128f::SIG_LEN;
    assert_eq!(q.len(), expect, "quote length {} != {}", q.len(), expect);
    let body = &q[..body_len];
    let ed_sig = Signature::from_slice(&q[body_len..body_len + ed_len]).unwrap();
    let slh_sig: [u8; slh_dsa_sha2_128f::SIG_LEN] =
        q[body_len + ed_len..].try_into().unwrap();

    let nonce = &q[..32];
    let svn = u64::from_le_bytes(q[32..40].try_into().unwrap());

    let ed_pk = PublicKey::from_slice(&fs::read(format!("{keydir}/ak_ed.pk")).unwrap()).unwrap();
    let ed_ok = ed_pk.verify(body, &ed_sig).is_ok();
    let pq_present = slh_sig.iter().any(|&b| b != 0);
    let slh_ok = if pq_present {
        let slh_pk_bytes: [u8; slh_dsa_sha2_128f::PK_LEN] =
            fs::read(format!("{keydir}/ak_slh.pk")).unwrap().try_into().unwrap();
        let slh_pk = slh_dsa_sha2_128f::PublicKey::try_from_bytes(&slh_pk_bytes).unwrap();
        slh_pk.verify(body, &slh_sig, AK_CTX)
    } else {
        false
    };
    // The nonce is now a fresh per-boot hardware-TRNG value (B-2), not the old
    // compile-time constant — so we DON'T compare it to CHALLENGE_NONCE. Real
    // freshness is proven by the interactive challenge/response (ephemeral-key)
    // path; this legacy quote check verifies the AK signatures over whatever
    // nonce the device chose and echoes it.
    println!("quote-verify:");
    println!("  nonce      {} (per-boot; freshness via challenge path)", hex(nonce));
    println!("  svn        {svn}");
    for i in 0..NUM_PCR {
        println!("  PCR{i}       {}", hex(&q[40 + 32 * i..40 + 32 * (i + 1)]));
    }
    println!("  AK ed25519 {}", if ed_ok { "OK" } else { "FAIL" });
    println!("  AK SLH-DSA {}", if pq_present { if slh_ok { "OK (quantum-safe)" } else { "FAIL" } } else { "deferred (not signed)" });
    if ed_ok && (!pq_present || slh_ok) {
        println!("  ATTESTATION: VALID — AK signatures verify over the quote (nonce echoed, not challenge-checked)");
        std::process::exit(0);
    } else {
        println!("  ATTESTATION: INVALID");
        std::process::exit(1);
    }
}

const EPH_CERT_CTX: &[u8] = b"HEQK-EPHCERT-v1";

/// Cert body the AK signs = eph_pk(32) || svn(8 LE) || device_id(8 LE) || PCRs.
/// Must match HBoot `attest::emit_ephemeral_cert` byte-for-byte.
fn cert_body(eph_pk: &[u8; 32], svn: u64, device_id: u64, pcr: &[u8]) -> Vec<u8> {
    let mut b = Vec::with_capacity(32 + 8 + 8 + pcr.len());
    b.extend_from_slice(eph_pk);
    b.extend_from_slice(&svn.to_le_bytes());
    b.extend_from_slice(&device_id.to_le_bytes());
    b.extend_from_slice(pcr);
    b
}

/// The public ephemeral-attestation bundle the device exports (NO secret key):
///   eph_ed_pk(32) | device_id(8) | svn(8) | ak_hw_bound(8) |
///   ak_ed_pk(32) | ak_slh_pk(32) | cert_ed_sig(64) | cert_slh_sig(SIG_LEN) | pcr(128)
fn bundle_len() -> usize {
    32 + 8 + 8 + 8 + 32 + 32 + 64 + slh_dsa_sha2_128f::SIG_LEN + 32 * NUM_PCR
}

/// Verify a device ephemeral bundle + enroll (TOFU) its per-device AK pubkey.
/// Returns true iff the hybrid AK cert over the ephemeral key verifies AND the
/// AK pubkey matches what was enrolled for this device_id (first sighting =
/// enrolled). This is exactly what a remote verifier does: bind THIS device's
/// AK to THIS device_id, and detect any later key swap.
fn verify_bundle(enroll_dir: &str, d: &[u8]) -> bool {
    assert_eq!(d.len(), bundle_len(), "bundle {} != {}", d.len(), bundle_len());
    let sig_len = slh_dsa_sha2_128f::SIG_LEN;
    let mut o = 0usize;
    let mut take = |n: usize| {
        let s = d[o..o + n].to_vec();
        o += n;
        s
    };
    let eph_pk: [u8; 32] = take(32).try_into().unwrap();
    let device_id = u64::from_le_bytes(take(8).try_into().unwrap());
    let svn = u64::from_le_bytes(take(8).try_into().unwrap());
    let hw_bound = u64::from_le_bytes(take(8).try_into().unwrap());
    let ak_ed_pk: [u8; 32] = take(32).try_into().unwrap();
    let ak_slh_pk: [u8; 32] = take(32).try_into().unwrap();
    let cert_ed_sig = Signature::from_slice(&take(64)).unwrap();
    let cert_slh_sig: [u8; slh_dsa_sha2_128f::SIG_LEN] = take(sig_len).try_into().unwrap();
    let pcr = take(32 * NUM_PCR);

    // Verify the hybrid AK cert over (eph_pk || svn || device_id || PCRs).
    let body = cert_body(&eph_pk, svn, device_id, &pcr);
    let mut ed_msg = Vec::new();
    ed_msg.extend_from_slice(EPH_CERT_CTX);
    ed_msg.extend_from_slice(&body);
    let ed_ok = PublicKey::from_slice(&ak_ed_pk)
        .and_then(|pk| pk.verify(&ed_msg, &cert_ed_sig).map(|_| true))
        .unwrap_or(false);
    let slh_ok = slh_dsa_sha2_128f::PublicKey::try_from_bytes(&ak_slh_pk)
        .map(|pk| pk.verify(&body, &cert_slh_sig, EPH_CERT_CTX))
        .unwrap_or(false);

    // TOFU enrollment keyed by device_id.
    let path = format!("{enroll_dir}/{device_id:016x}.ak");
    let mut enroll_ok = true;
    let enroll_status: String = match fs::read(&path) {
        Ok(existing) if existing.len() == 64 => {
            if existing[..32] == ak_ed_pk && existing[32..] == ak_slh_pk {
                "recognized (matches enrolled AK)".into()
            } else {
                enroll_ok = false;
                "KEY MISMATCH — this device_id was enrolled with a DIFFERENT AK (spoof / re-provision?)".into()
            }
        }
        _ => {
            let mut rec = Vec::new();
            rec.extend_from_slice(&ak_ed_pk);
            rec.extend_from_slice(&ak_slh_pk);
            fs::create_dir_all(enroll_dir).ok();
            fs::write(&path, &rec).expect("write enrollment");
            "ENROLLED (first sighting — trust-on-first-use)".into()
        }
    };

    println!("attest-verify:");
    println!("  device_id    {device_id:#018x}");
    println!("  AK           {} (ak_ed_pk {})", if hw_bound != 0 { "hardware-bound (OTP-derived)" } else { "software" }, hex(&ak_ed_pk[..6]));
    println!("  svn          {svn}");
    for i in 0..NUM_PCR {
        println!("  PCR{i}         {}", hex(&pcr[32 * i..32 * (i + 1)]));
    }
    println!("  AK cert ed   {}", if ed_ok { "OK" } else { "FAIL" });
    println!("  AK cert slh  {}", if slh_ok { "OK (quantum-safe)" } else { "FAIL" });
    println!("  enrollment   {enroll_status}");
    let valid = ed_ok && slh_ok && enroll_ok;
    println!("  ATTESTATION: {}", if valid { "VALID — per-device AK certifies this boot's ephemeral key" } else { "INVALID" });
    valid
}

/// `attest-verify <enroll_dir> <bundle_file>` — verify + enroll a device bundle.
fn attest_verify(enroll_dir: &str, bundle_file: &str) {
    let d = fs::read(bundle_file).expect("read bundle");
    std::process::exit(if verify_bundle(enroll_dir, &d) { 0 } else { 1 });
}

/// `attest-selftest` — generate a synthetic per-device AK + ephemeral key + cert
/// (mimicking HBoot) and exercise the verifier: a genuine bundle VERIFIES +
/// enrolls; a tampered bundle FAILS; a different AK on the same device_id is
/// caught as a KEY MISMATCH. Proves the verify/enroll logic with no hardware.
fn attest_selftest() {
    let dir = std::env::temp_dir().join(format!("heqk-enroll-selftest-{}", std::process::id()));
    let dir = dir.to_str().unwrap();
    fs::remove_dir_all(dir).ok();

    let build = |device_id: u64, ak_ed: &KeyPair, ak_slh_sk: &slh_dsa_sha2_128f::PrivateKey,
                 ak_slh_pk: &[u8; 32]| -> Vec<u8> {
        let eph = KeyPair::generate();
        let svn = 1u64;
        let pcr = vec![0u8; 32 * NUM_PCR];
        let eph_pk: [u8; 32] = eph.pk.as_ref().try_into().unwrap();
        let body = cert_body(&eph_pk, svn, device_id, &pcr);
        let mut ed_msg = Vec::new();
        ed_msg.extend_from_slice(EPH_CERT_CTX);
        ed_msg.extend_from_slice(&body);
        let cert_ed = ak_ed.sk.sign(&ed_msg, None);
        let cert_slh: [u8; slh_dsa_sha2_128f::SIG_LEN] =
            ak_slh_sk.try_sign(&body, EPH_CERT_CTX, false).unwrap();
        let mut b = Vec::new();
        b.extend_from_slice(&eph_pk);
        b.extend_from_slice(&device_id.to_le_bytes());
        b.extend_from_slice(&svn.to_le_bytes());
        b.extend_from_slice(&1u64.to_le_bytes()); // hw_bound
        b.extend_from_slice(ak_ed.pk.as_ref());
        b.extend_from_slice(ak_slh_pk);
        b.extend_from_slice(cert_ed.as_ref());
        b.extend_from_slice(&cert_slh);
        b.extend_from_slice(&pcr);
        b
    };

    let ak_ed = KeyPair::generate();
    let (ak_slh_pk_o, ak_slh_sk) = slh_dsa_sha2_128f::try_keygen().unwrap();
    let ak_slh_pk: [u8; 32] = ak_slh_pk_o.into_bytes();

    println!("== 1. genuine bundle (expect VALID + ENROLLED) ==");
    let good = build(0xd00d_1234, &ak_ed, &ak_slh_sk, &ak_slh_pk);
    assert!(verify_bundle(dir, &good), "genuine bundle must verify");

    println!("\n== 2. same device again (expect recognized) ==");
    assert!(verify_bundle(dir, &good), "re-verify must recognize");

    println!("\n== 3. tampered PCR (expect INVALID) ==");
    let mut bad = good.clone();
    let plen = bad.len();
    bad[plen - 1] ^= 0x01; // flip a PCR bit -> cert no longer covers it
    assert!(!verify_bundle(dir, &bad), "tampered bundle must fail");

    println!("\n== 4. DIFFERENT AK on same device_id (expect KEY MISMATCH) ==");
    let ak_ed2 = KeyPair::generate();
    let (ak_slh_pk2_o, ak_slh_sk2) = slh_dsa_sha2_128f::try_keygen().unwrap();
    let ak_slh_pk2: [u8; 32] = ak_slh_pk2_o.into_bytes();
    let swapped = build(0xd00d_1234, &ak_ed2, &ak_slh_sk2, &ak_slh_pk2);
    assert!(!verify_bundle(dir, &swapped), "AK swap must be rejected");

    fs::remove_dir_all(dir).ok();
    println!("\nattest-selftest: PASS — verify + TOFU-enroll + tamper + key-swap all correct");
}

fn payload_hash(path: &str) -> [u8; 32] {
    let data = fs::read(path).expect("read payload");
    let mut h = Sha256::new();
    h.update(&data);
    h.finalize().into()
}

fn keygen(keydir: &str) {
    fs::create_dir_all(keydir).unwrap();

    // Classical.
    let ed = KeyPair::generate();
    fs::write(format!("{keydir}/ed25519.sk"), ed.sk.as_ref()).unwrap();
    fs::write(format!("{keydir}/ed25519.pk"), ed.pk.as_ref()).unwrap();

    // Post-quantum (SLH-DSA).
    let (pq_pk, pq_sk) = slh_dsa_sha2_128s::try_keygen().expect("slh keygen");
    fs::write(format!("{keydir}/slhdsa.sk"), pq_sk.into_bytes()).unwrap();
    let pq_pk_bytes = pq_pk.into_bytes();
    fs::write(format!("{keydir}/slhdsa.pk"), pq_pk_bytes).unwrap();

    // Emit the trusted-key Rust source HBoot compiles in (root of trust).
    let mut src = String::new();
    src.push_str("// GENERATED by heqk-sign keygen — HBoot's embedded root of trust.\n");
    src.push_str("// The public keys live in the boot manager binary, never in the\n");
    src.push_str("// signed image (else an attacker could swap key + signature together).\n\n");
    src.push_str(&rust_array("ED25519_PUBKEY", ed.pk.as_ref()));
    src.push_str(&rust_array("SLHDSA_PUBKEY", &pq_pk_bytes));
    fs::write(format!("{keydir}/trusted_keys.rs"), src).unwrap();

    println!("keygen: wrote ed25519 + SLH-DSA-SHA2-128s keypairs to {keydir}");
    println!("        trusted_keys.rs ({} + {} byte pubkeys) ready to embed in HBoot",
        ed.pk.as_ref().len(), pq_pk_bytes.len());
}

fn rust_array(name: &str, bytes: &[u8]) -> String {
    let mut s = format!("pub const {name}: [u8; {}] = [\n", bytes.len());
    for chunk in bytes.chunks(12) {
        s.push_str("    ");
        for b in chunk {
            s.push_str(&format!("0x{b:02x}, "));
        }
        s.push('\n');
    }
    s.push_str("];\n\n");
    s
}

/// The signed message binds the SVN: SHA-256( LE64(svn) || sha256(payload) ).
/// Must match boot_abi::signed_message_input + HBoot's second SHA-256.
fn signed_message(payload_hash: &[u8; 32], svn: u64) -> [u8; 32] {
    let mut buf = [0u8; 40];
    buf[..8].copy_from_slice(&svn.to_le_bytes());
    buf[8..].copy_from_slice(payload_hash);
    let mut h = Sha256::new();
    h.update(buf);
    h.finalize().into()
}

fn sign(keydir: &str, payload: &str, svn: u64, ed_out: &str, pq_out: &str) {
    let ph = payload_hash(payload);
    let msg = signed_message(&ph, svn);

    // ed25519.
    let sk = SecretKey::from_slice(&fs::read(format!("{keydir}/ed25519.sk")).unwrap()).unwrap();
    let ed_sig: Signature = sk.sign(msg, Some(Noise::default()));
    fs::write(ed_out, ed_sig.as_ref()).unwrap();

    // SLH-DSA.
    let sk_bytes: [u8; slh_dsa_sha2_128s::SK_LEN] =
        fs::read(format!("{keydir}/slhdsa.sk")).unwrap().try_into().unwrap();
    let pq_sk = slh_dsa_sha2_128s::PrivateKey::try_from_bytes(&sk_bytes).unwrap();
    let pq_sig = pq_sk.try_sign(&msg, CTX, true).expect("slh sign");
    fs::write(pq_out, pq_sig).unwrap();

    // Self-check both before we hand the image off.
    let ed_pk = PublicKey::from_slice(&fs::read(format!("{keydir}/ed25519.pk")).unwrap()).unwrap();
    assert!(ed_pk.verify(msg, &ed_sig).is_ok(), "ed25519 self-verify failed");
    let pq_pk_bytes: [u8; slh_dsa_sha2_128s::PK_LEN] =
        fs::read(format!("{keydir}/slhdsa.pk")).unwrap().try_into().unwrap();
    let pq_pk = slh_dsa_sha2_128s::PublicKey::try_from_bytes(&pq_pk_bytes).unwrap();
    assert!(pq_pk.verify(&msg, &pq_sig, CTX), "SLH-DSA self-verify failed");

    println!("sign: payload sha256={} svn={svn}", hex(&ph));
    println!("      signed message (binds svn)={}", hex(&msg));
    println!("      ed25519 sig {} B -> {ed_out}", ed_sig.as_ref().len());
    println!("      SLH-DSA sig {} B -> {pq_out}", pq_sig.len());
    println!("      both self-verified OK");
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// Mirror HBoot's exact verify path, including anti-rollback: recompute the
/// SVN-bound signed message, require BOTH signatures against the trusted keys,
/// AND svn >= floor. Exit 0 only if all hold — proves accept/reject on host.
fn verify(keydir: &str, payload: &str, svn: u64, floor: u64, ed_sig: &str, pq_sig: &str) {
    let ph = payload_hash(payload);
    let msg = signed_message(&ph, svn);

    let ed_pk = PublicKey::from_slice(&fs::read(format!("{keydir}/ed25519.pk")).unwrap()).unwrap();
    let ed_sig = Signature::from_slice(&fs::read(ed_sig).unwrap()).unwrap();
    let ed_ok = ed_pk.verify(msg, &ed_sig).is_ok();

    let pq_pk_bytes: [u8; slh_dsa_sha2_128s::PK_LEN] =
        fs::read(format!("{keydir}/slhdsa.pk")).unwrap().try_into().unwrap();
    let pq_pk = slh_dsa_sha2_128s::PublicKey::try_from_bytes(&pq_pk_bytes).unwrap();
    let pq_bytes: [u8; slh_dsa_sha2_128s::SIG_LEN] =
        fs::read(pq_sig).unwrap().try_into().unwrap();
    let pq_ok = pq_pk.verify(&msg, &pq_bytes, CTX);

    let svn_ok = svn >= floor;
    println!("verify: payload sha256={} svn={svn} floor={floor}", hex(&ph));
    println!("        ed25519   {}", if ed_ok { "OK" } else { "FAIL" });
    println!("        SLH-DSA   {}", if pq_ok { "OK" } else { "FAIL" });
    println!("        anti-roll {}", if svn_ok { "OK" } else { "FAIL (rollback)" });
    if ed_ok && pq_ok && svn_ok {
        println!("        secure boot: PASS");
        std::process::exit(0);
    } else {
        println!("        secure boot: FAIL");
        std::process::exit(1);
    }
}

fn main() {
    let a: Vec<String> = std::env::args().collect();
    let arg = |i: usize| a.get(i).map(String::as_str).unwrap_or("");
    match a.get(1).map(String::as_str) {
        Some("keygen") => keygen(&a[2]),
        Some("akgen") => akgen(&a[2]),
        // sign <keydir> <payload> <svn> <ed.sig> <pq.sig>
        Some("sign") => sign(&a[2], &a[3], a[4].parse().expect("svn"), &a[5], &a[6]),
        // verify <keydir> <payload> <svn> <floor> <ed.sig> <pq.sig>
        Some("verify") => verify(&a[2], &a[3], arg(4).parse().expect("svn"),
            arg(5).parse().expect("floor"), &a[6], &a[7]),
        // quote-verify <keydir> <quote-file>   (legacy: software-AK boot quote)
        Some("quote-verify") => quote_verify(&a[2], &a[3]),
        // attest-verify <enroll_dir> <bundle-file>   (per-device AK cert + TOFU enroll)
        Some("attest-verify") => attest_verify(&a[2], &a[3]),
        Some("attest-selftest") => attest_selftest(),
        _ => {
            eprintln!("usage:\n  heqk-sign keygen <keydir>\n  heqk-sign sign   <keydir> <payload> <svn> <ed.sig> <pq.sig>\n  heqk-sign verify <keydir> <payload> <svn> <floor> <ed.sig> <pq.sig>\n  heqk-sign attest-verify <enroll_dir> <bundle-file>\n  heqk-sign attest-selftest");
            std::process::exit(2);
        }
    }
}
