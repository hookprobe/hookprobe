#!/usr/bin/env python3
"""Generate os/kernel/kernel/src/fpdb.rs — the device-fingerprint tables heqk uses for discovery — from the
legacy V1 Fingerbank module (literal dicts only: parsed with `ast`, never imported or executed).

    python3 -I os/build/fpgen/gen_fpdb.py legacy/v1/products/fortress/lib/fingerbank.py > os/kernel/kernel/src/fpdb.rs

Tables (all sorted for binary search; strings sanitised to printable ASCII without quotes/backslashes):
  OPT55     — DHCP option-55 parameter-request-list string -> (name, vendor, category, os, confidence %)
  OUI       — 3-byte OUI -> vendor index into VENDORS
  OUI_DEV   — 3-byte OUI that pins a specific device -> (name, vendor, category, os, confidence %)
Merge order follows the legacy `build_fingerprint_database()` (later sources override earlier ones).
"""
import ast
import hashlib
import sys

SRC = sys.argv[1]
text = open(SRC, encoding='utf-8').read()
tree = ast.parse(text)
lit = {}
for n in tree.body:
    if isinstance(n, ast.Assign) and isinstance(n.value, ast.Dict):
        for t in n.targets:
            if isinstance(t, ast.Name):
                try:
                    lit[t.id] = ast.literal_eval(n.value)
                except ValueError:
                    pass

ORDER = ['IOT_FINGERPRINTS', 'NETWORK_EQUIPMENT_FINGERPRINTS', 'LINUX_FINGERPRINTS', 'SMART_HUB_FINGERPRINTS',
         'CAMERA_FINGERPRINTS', 'PRINTER_FINGERPRINTS', 'GAMING_FINGERPRINTS', 'SMART_TV_FINGERPRINTS',
         'SMART_SPEAKER_FINGERPRINTS', 'ANDROID_FINGERPRINTS', 'WINDOWS_FINGERPRINTS', 'APPLE_FINGERPRINTS']


def clean(s, n=40):
    s = str(s or '')
    return ''.join(c for c in s if 32 <= ord(c) < 127 and c not in '"\\')[:n]


def norm_prl(k):
    parts = [p.strip() for p in str(k).split(',') if p.strip()]
    if not parts or not all(p.isdigit() and int(p) < 256 for p in parts):
        return None
    return ','.join(str(int(p)) for p in parts)


opt55 = {}
for name in ORDER:
    for k, v in lit.get(name, {}).items():
        p = norm_prl(k)
        if p is None or not isinstance(v, dict):
            continue
        opt55[p] = (clean(v.get('name')), clean(v.get('vendor')), clean(v.get('category'), 24), clean(v.get('os'), 24),
                    int(round(float(v.get('confidence', 0.5)) * 100)))


def oui(k):
    h = str(k).replace(':', '').replace('-', '').upper()
    if len(h) != 6 or any(c not in '0123456789ABCDEF' for c in h):
        return None
    return bytes.fromhex(h)


vendors = []
vidx = {}
ouis = {}
for k, v in lit.get('OUI_DATABASE', {}).items():
    o = oui(k)
    if o is None:
        continue
    vn = clean(v, 32)
    if vn not in vidx:
        vidx[vn] = len(vendors)
        vendors.append(vn)
    ouis[o] = vidx[vn]

oui_dev = {}
for k, v in lit.get('SPECIFIC_OUI_DEVICES', {}).items():
    o = oui(k)
    if o is None or not isinstance(v, dict):
        continue
    oui_dev[o] = (clean(v.get('name')), clean(v.get('vendor')), clean(v.get('category'), 24), clean(v.get('os'), 24),
                  int(round(float(v.get('confidence', 0.5)) * 100)))

src_sha = hashlib.sha256(text.encode()).hexdigest()[:16]
o = []
o.append('//! GENERATED by os/build/fpgen/gen_fpdb.py from the legacy V1 Fingerbank tables — do not edit by hand.')
o.append(f'//! Source sha256 {src_sha}; {len(opt55)} option-55 fingerprints, {len(ouis)} OUIs ({len(vendors)} vendors), {len(oui_dev)} device-pinning OUIs.')
o.append('#![allow(dead_code)]')
o.append('')
o.append('/// (name, vendor, category, os, confidence %)')
o.append('pub type Fp = (&\'static str, &\'static str, &\'static str, &\'static str, u8);')
o.append('')
o.append('/// DHCP option-55 parameter-request list (comma-joined decimals) -> fingerprint. Sorted by key.')
o.append('pub static OPT55: &[(&str, Fp)] = &[')
for k in sorted(opt55):
    a = opt55[k]
    o.append(f'    ("{k}", ("{a[0]}", "{a[1]}", "{a[2]}", "{a[3]}", {min(a[4], 100)})),')
o.append('];')
o.append('')
o.append('pub static VENDORS: &[&str] = &[')
for vn in vendors:
    o.append(f'    "{vn}",')
o.append('];')
o.append('')
o.append('/// OUI -> index into VENDORS. Sorted by OUI.')
o.append('pub static OUI: &[([u8; 3], u16)] = &[')
for k in sorted(ouis):
    o.append(f'    ([0x{k[0]:02x}, 0x{k[1]:02x}, 0x{k[2]:02x}], {ouis[k]}),')
o.append('];')
o.append('')
o.append('/// OUIs that identify one specific device type. Sorted by OUI.')
o.append('pub static OUI_DEV: &[([u8; 3], Fp)] = &[')
for k in sorted(oui_dev):
    a = oui_dev[k]
    o.append(f'    ([0x{k[0]:02x}, 0x{k[1]:02x}, 0x{k[2]:02x}], ("{a[0]}", "{a[1]}", "{a[2]}", "{a[3]}", {min(a[4], 100)})),')
o.append('];')
print('\n'.join(o))
