#!/usr/bin/env python3
"""Regenerate the validation-matrix section of README.md from heqk-validation.html.

The section between the VALIDATION-MATRIX:BEGIN/END markers is rewritten in
full; everything outside is untouched. Run from anywhere in the repo; CI runs
it on every push to main that touches heqk-validation.html.
"""
import re
import subprocess
import sys
from datetime import date, datetime, timezone
from html import unescape
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HTML = ROOT / "heqk-validation.html"
README = ROOT / "README.md"
BEGIN = "<!-- VALIDATION-MATRIX:BEGIN (generated by tools/gen-readme-matrix.py — edit heqk-validation.html, not this section) -->"
END = "<!-- VALIDATION-MATRIX:END -->"


class Grab(HTMLParser):
    """Collect the text of an element, dropping 'new' badges, keeping code ticks."""

    def __init__(self):
        super().__init__()
        self.out = []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        cls = dict(attrs).get("class", "")
        if tag == "span" and "new" in cls.split():
            self.skip += 1
        elif tag == "small" and not self.skip:
            self.out.append(" — ")
        elif tag == "code" and not self.skip:
            self.out.append("`")

    def handle_endtag(self, tag):
        if tag == "span" and self.skip:
            self.skip -= 1
        elif tag == "code" and not self.skip:
            self.out.append("`")

    def handle_data(self, data):
        if not self.skip:
            self.out.append(data)


def text(html):
    g = Grab()
    g.feed(html)
    t = unescape("".join(g.out))
    return re.sub(r"\s+", " ", t).strip().replace("|", "\\|")


def matrix_markdown(src):
    md = []
    stats = re.findall(r'<div class="n">(\d+)</div><div class="l">([^<]+)</div>', src)
    if stats:
        md += [
            "| " + " | ".join(f"**{n}**" for n, _ in stats) + " |",
            "|" + "---|" * len(stats),
            "| " + " | ".join(unescape(l).strip() for _, l in stats) + " |",
            "",
        ]
    md += [
        "Legend: **Metal** = validated on CM5 (BCM2712) hardware · **QEMU** = validated "
        "under emulation · **HW-gated** = code complete, blocked on hardware · "
        "**Planned** = designed & gated, not yet built.",
        "",
    ]
    for sec in re.findall(r"<section>(.*?)</section>", src, re.S):
        m = re.search(
            r'sec-no">([^<]+)</span><h2>(.*?)</h2><span class="desc">(.*?)</span>', sec, re.S
        )
        if not m:
            continue
        md += [f"### {m.group(1).strip()} · {text(m.group(2))}", "", f"*{text(m.group(3))}*", ""]
        for note in re.findall(r'<div class="note"[^>]*>(.*?)</div>', sec, re.S):
            md += ["> " + text(note), ""]
        rows = re.findall(r'<tr class="(\w+)">(.*?)</tr>', sec, re.S)
        if rows:
            md += ["| Feature | Phase | Proves | Validated | Marker |", "|---|---|---|---|---|"]
            for _, row in rows:
                tds = re.findall(r"<td[^>]*>(.*?)</td>", row, re.S)
                if len(tds) != 5:
                    continue
                feat, ph, proves, _, marker = (text(t) for t in tds)
                pills = re.findall(r'class="pill \w+">([^<]+)</span>', tds[3])
                env = " · ".join(f"**{p}**" if p == "Metal" else p for p in pills)
                md.append(f"| {feat} | {ph} | {proves} | {env} | {marker} |")
            md.append("")
    return "\n".join(md).rstrip()


def as_of_date():
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cI", "--", HTML.name],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
        if out:
            return datetime.fromisoformat(out).astimezone(timezone.utc).date().isoformat()
    except Exception:
        pass
    return date.today().isoformat()


def main():
    src = HTML.read_text()
    readme = README.read_text()
    if BEGIN not in readme or END not in readme:
        sys.exit(f"error: {BEGIN!r} / {END!r} markers not found in README.md")
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    section = (
        f"{BEGIN}\n\n"
        f"*As of {as_of_date()}. QEMU gates are re-derived live from a `./validate.sh` run; "
        "metal rows carry their last-recorded boot state on CM5. Generated from "
        "`heqk-validation.html` (built by `tools/gen-validation.py`); this section is "
        "refreshed automatically by CI.*\n\n"
        f"{matrix_markdown(src)}\n\n{END}"
    )
    updated = head + section + tail
    if updated != readme:
        README.write_text(updated)
        print("README.md updated")
    else:
        print("README.md already up to date")


if __name__ == "__main__":
    main()
