#!/usr/bin/env python3
"""Regenerate kernel/src/testdata/hqcfg_vectors.rs from hqcfg-vectors.json (the shared HQCFG1 vectors) for the
in-kernel [P-cfgbundle] self-test. Run after `hqcfg.py vectors`:  python3 -I tools/vectors/hqcfg-vectors-rs.py"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, "hqcfg-vectors.json")))
out = ["// GENERATED by os/kernel/tools/vectors/hqcfg-vectors-rs.py from hqcfg-vectors.json — do not edit.",
       "pub struct Case { pub name: &'static str, pub bundle: &'static [u8], pub sig: &'static [u8], pub floor: u64, pub accept: bool }",
       "pub const PK: [u8; 32] = [%s];" % ", ".join(str(b) for b in bytes.fromhex(d["public_key"])),
       "pub const GEN_FULL: u64 = %d;" % int(d["generation_full"])]
secs = d["sections_full"]  # {name: body}; ranges follow the 48-B header + 4-B table rows, in kind order
kinds = {"wan": 1, "wifi": 4, "policy": 5}
order = sorted(secs, key=lambda n: kinds[n])
off = 48 + 4 * len(order)
rows = []
for n in order:
    ln = len(secs[n].encode())
    rows.append("(%d, %d, %d)" % (kinds[n], off, ln))
    off += ln
out.append("pub const SECTIONS_FULL: [(u8, usize, usize); %d] = [%s];" % (len(rows), ", ".join(rows)))
out.append("pub static CASES: &[Case] = &[")
for name, c in sorted(d["cases"].items()):
    acc = c["accept"] if isinstance(c["accept"], bool) else str(c["accept"]).lower() == "true"
    out.append('    Case { name: "%s", bundle: &[%s], sig: &[%s], floor: %d, accept: %s },' % (
        name, ", ".join(str(b) for b in bytes.fromhex(c["bundle"])), ", ".join(str(b) for b in bytes.fromhex(c["sig"])),
        int(c["floor"]), "true" if acc else "false"))
out.append("];")
dst = os.path.join(here, "..", "..", "kernel", "src", "testdata", "hqcfg_vectors.rs")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(dst), len(d["cases"]), "cases")
