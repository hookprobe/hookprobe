fn json(scratch: &mut [u8], f: impl FnOnce(&mut JsonBuf)) -> Response {
    let mut w = JsonBuf::new(scratch);
    f(&mut w);
    let ok = !w.overflow;
    let len = w.len;
    if ok {
        Response { status: 200, ctype: "application/json", body: Body::Scratch(len), location: None, set_cookie: None }
    } else {
        let mut w = JsonBuf::new(scratch);
        w.raw("{\"error\":\"response too large\"}");
        Response { status: 500, ctype: "application/json", body: Body::Scratch(w.len), location: None, set_cookie: None }
    }
}

/// `set_cookie` sentinel: expire the session cookie (logout).
pub const CLEAR_COOKIE: [u8; 32] = [b'-'; 32];

/// Route one request against the device state, enforcing owner authentication (ADR 0037 D3).
/// `scratch` receives rendered JSON; `rand16` mints a session id on a successful login.
pub fn handle(req: &Req, st: &McState, auth: &mut Auth, now_ms: u64, rand16: impl FnOnce() -> Option<[u8; 16]>, scratch: &mut [u8]) -> Response {
    // Public: the login page, the login action, and a minimal health probe.
    match (req.path, req.get, req.post) {
        ("/login", true, _) => return Response::page(200, LOGIN_HTML),
        ("/api/login", _, true) => return login(req, auth, now_ms, rand16, scratch),
        // Parity G28: logout ends this session (`?all=1`: every session) and expires the cookie.
        ("/api/logout", _, true) => {
            let all = query_u32(req.query, "all") == Some(1);
            let ended = auth.logout(req.session, all, now_ms);
            let mut r = json(scratch, |w| w.raw(if ended { "{\"logged_out\":true}" } else { "{\"logged_out\":false}" }));
            r.set_cookie = Some(CLEAR_COOKIE);
            return if ended { r } else { r.with_status(401) };
        }
        ("/api/health", true, _) if !auth.check(req.session, now_ms) => {
            let claimed = auth.claimed();
            return json(scratch, |w| {
                w.raw("{\"status\":\"ok\",\"substrate\":\"heqk\",\"claimed\":");
                w.raw(if claimed { "true" } else { "false" });
                w.raw("}");
            });
        }
        _ => {}
    }
    let api = req.path.starts_with("/api/");
    if !auth.claimed() {
        return if api {
            json(scratch, |w| w.raw("{\"error\":\"device not claimed: flash it with the HookProbe flasher to set the owner key\"}")).with_status(403)
        } else {
            Response::page(403, UNCLAIMED_HTML)
        };
    }
    if !auth.check(req.session, now_ms) {
        return if api {
            json(scratch, |w| w.raw("{\"error\":\"sign in required\"}")).with_status(401)
        } else {
            Response { status: 302, ctype: "text/plain", body: Body::Scratch(0), location: Some("/login"), set_cookie: None }
        };
    }
    if !req.get {
        return json(scratch, |w| w.raw("{\"error\":\"method not allowed\"}")).with_status(405);
    }
    let limit = |dflt: u32, max: u32| query_u32(req.query, "limit").unwrap_or(dflt).clamp(1, max) as usize;
    match req.path {
        "/api/detections" => json(scratch, |w| st.render_detections(limit(200, 500), w)),
        "/api/incidents" => json(scratch, |w| st.render_incidents(limit(50, 500), w)),
        "/api/qsecbit" => json(scratch, |w| st.render_qsecbit(limit(20, 1000), w)),
        "/api/devices" => json(scratch, |w| st.render_devices(limit(200, 256), w)),
        "/api/dns" => json(scratch, |w| crate::shield::render(w, &|t| st.epoch_ms(t), limit(50, 256))),
        "/api/flows" => json(scratch, |w| st.render_flows(st.ticks_at_ms(now_ms), limit(100, 256), w)),
        p if p.starts_with("/api/incidents/") => {
            let rest = &p["/api/incidents/".len()..];
            let (id, sub) = match rest.find('/') { Some(i) => (&rest[..i], &rest[i..]), None => (rest, "") };
            match (McState::parse_incident_id(id), sub) {
                (Some(src), "") => {
                    let mut found = true;
                    let r = json(scratch, |w| found = st.render_incident(src, w));
                    if found { r } else { json(scratch, |w| w.raw("{\"error\":\"no such incident\"}")).with_status(404) }
                }
                (Some(src), "/timeline") => json(scratch, |w| st.render_timeline(src, st.ticks_at_ms(now_ms), w)),
                // heqk has no host process telemetry (no EDR agent on the clients): an honest empty tree.
                (Some(src), "/processes") => json(scratch, |w| {
                    use core::fmt::Write;
                    let _ = write!(w, "{{\"incident\":\"inc:heqk:{}.{}.{}.{}\",\"found\":true,\"process_count\":0,\"roots\":[]}}",
                        src >> 24, (src >> 16) & 0xff, (src >> 8) & 0xff, src & 0xff);
                }),
                _ => json(scratch, |w| w.raw("{\"error\":\"no such incident\"}")).with_status(404),
            }
        }
        // No engine registry on heqk yet: an EMPTY list keeps every engine row honestly badged
        // "mock" in the Detect UI rather than inventing live engines.
        "/api/engines" => json(scratch, |w| st.render_engines((crate::shield::block_len(), crate::shield::totals().1), w)),
        "/api/evidence/stats" => json(scratch, |w| {
            let mut nf = 0usize;
            arch_aarch64::nat::for_each_flow(st.ticks_at_ms(now_ms), &mut |_| nf += 1);
            st.render_evidence_stats(nf, crate::shield::totals().0, w)
        }),
        "/api/evidence/graph" => {
            let mut nb = [0u8; 96];
            match query_str(req.query, "node", &mut nb) {
                Some(node) => {
                    let mut found = true;
                    let r = json(scratch, |w| found = st.render_graph(node, w));
                    if found { r } else { json(scratch, |w| w.raw("{\"error\":\"no such node\"}")).with_status(404) }
                }
                None => json(scratch, |w| w.raw("{\"error\":\"node= required\"}")).with_status(400),
            }
        }
        "/api/reports" => json(scratch, |w| st.render_reports(limit(200, 32), w)),
        // Parity G7/G9: the operator-signed intel + device-policy files and what they matched.
        "/api/intel" => json(scratch, |w| {
            use core::fmt::Write;
            let i = crate::ioc::info();
            let d = crate::devpolicy::info();
            let dn = crate::devpolicy::denied();
            let f = |x: u8| ["none", "loaded", "refused"][x as usize % 3];
            let _ = write!(w, "{{\"ioc\":{{\"file\":\"{}\",\"signed\":{},\"generation\":{},\"ipv4_prefixes\":{},\"domains\":{},\"skipped_lines\":{},\"mode\":\"detect-only\"}},\"devices\":{{\"file\":\"{}\",\"signed\":{},\"generation\":{},\"entries\":{},\"skipped_lines\":{},\"denied\":{{\"internet_only\":{},\"lan_only\":{},\"quarantine\":{}}}}}}}",
                f(i.file), i.signed, i.generation, crate::ioc::v4_len(), crate::ioc::dom_len(), i.skipped,
                f(d.file), d.signed, d.generation, crate::devpolicy::len(), d.skipped, dn[1], dn[2], dn[3]);
        }),
        // Parity G23: who the device is enforcing against RIGHT NOW (read-only; everything self-reverts).
        "/api/enforcement" => json(scratch, |w| {
            use core::fmt::Write;
            w.raw("{\"policy\":\"observe by default; only a confirmed scan, a malformed frame, an L1/L2 flood or resource exhaustion is acted on, and every action self-reverts (ADR 0023)\",\"sources\":[");
            let mut k = 0;
            crate::ratelimit::for_each_scan_source(&mut |x| {
                let s = x.src;
                let _ = write!(w, "{}{{\"ip\":\"{}.{}.{}.{}\",\"state\":\"{}\",\"reason\":\"port scan\",\"distinct_ports\":{},\"established\":{},\"expires_in_s\":{}}}",
                    if k > 0 { "," } else { "" }, s >> 24, (s >> 16) & 0xff, (s >> 8) & 0xff, s & 0xff,
                    ["watching", "rate_limited", "quarantined"][x.level as usize % 3], x.distinct, x.established, x.expires_in);
                k += 1;
            });
            let _ = write!(w, "],\"count\":{}}}", k);
        }),
        p if p.starts_with("/api/reports/") => {
            // `rep:heqk:IP` (any `%3A` escaping) names the incident `inc:heqk:IP`
            let id = &p["/api/reports/".len()..];
            let mut ib = [0u8; 96];
            let n = id.len().min(ib.len());
            ib[..n].copy_from_slice(&id.as_bytes()[..n]);
            if ib[..n].starts_with(b"rep") {
                ib[..3].copy_from_slice(b"inc");
            }
            match core::str::from_utf8(&ib[..n]).ok().and_then(McState::parse_incident_id) {
                Some(src) => {
                    let mut found = true;
                    let r = json(scratch, |w| found = st.render_report(src, st.ticks_at_ms(now_ms), w));
                    if found { r } else { json(scratch, |w| w.raw("{\"error\":\"no such report\"}")).with_status(404) }
                }
                None => json(scratch, |w| w.raw("{\"error\":\"no such report\"}")).with_status(404),
            }
        }
        "/api/health" => json(scratch, |w| {
            use core::fmt::Write;
            // An unarmed rule plane (0 active rules) passes everything — report it, never hide it.
            let rules = crate::rules::active_rules();
            let now_epoch = st.epoch_at_ms(now_ms);
            let _ = write!(w, "{{\"status\":\"{}\",\"substrate\":\"heqk\",\"mode\":\"{}\",\"clock\":\"{}\",\"rules_active\":{},\"seen\":{},\"forwarded\":{},\"dropped\":{},\"detections\":{},\"hosts_active\":{},\"detections_cap\":{},\"oldest_detection\":{},\"sealed_cap\":{}",
                if rules == 0 { "degraded: rule plane not armed" } else { "ok" },
                if st.cloud_linked { "cloud-linked" } else { "standalone" },
                if st.clock_synced { "ntp" } else { "unsynced" }, rules, st.seen, st.forwarded, st.dropped, st.detections(),
                st.hosts_active(now_epoch), st.retention().1, st.retention().2 / 1000, st.sealed_cap);
            if let Some(f) = st.wan {
                let _ = write!(w, ",\"wan\":{{\"up\":{},\"ip\":\"{}.{}.{}.{}\",\"mode\":\"{}\",\"ipv6\":{},\"clients\":{},\"pkts_out\":{},\"pkts_in\":{},\"dns_inspected\":{},\"dns_blocked\":{},\"blocklist\":{}}}",
                    f.up, f.ip[0], f.ip[1], f.ip[2], f.ip[3], ["dhcp", "static", "pppoe"][(f.mode as usize).min(2)], f.ipv6, f.clients, f.pkts_out, f.pkts_in, f.dns_inspected, f.dns_blocked, f.blocklist);
            }
            w.raw("}");
        }),
        "/api/stream" => Response { status: 200, ctype: "text/event-stream", body: Body::Sse, location: None, set_cookie: None },
        p if p.starts_with("/api/") => json(scratch, |w| w.raw("{\"error\":\"not implemented on heqk\"}")).with_status(404),
        p => match asset_for(p) {
            Some(a) => Response { status: 200, ctype: a.ctype, body: Body::Static(a.body), location: None, set_cookie: None },
            None => json(scratch, |w| w.raw("{\"error\":\"not found\"}")).with_status(404),
        },
    }
}

/// `POST /api/login` with a form body `token=<owner key>` (the key alphabet needs no URL decoding).
fn login(req: &Req, auth: &mut Auth, now_ms: u64, rand16: impl FnOnce() -> Option<[u8; 16]>, scratch: &mut [u8]) -> Response {
    let body = core::str::from_utf8(req.body).unwrap_or("");
    let token = body.split('&').find_map(|kv| kv.strip_prefix("token=")).unwrap_or("").trim();
    match auth.login(token.as_bytes(), now_ms, rand16) {
        Ok(id) => {
            let mut hex = [0u8; 32];
            mcauth::session_hex(&id, &mut hex);
            Response { status: 303, ctype: "text/plain", body: Body::Scratch(0), location: Some("/"), set_cookie: Some(hex) }
        }
        Err(LoginErr::Unclaimed) => Response::page(403, UNCLAIMED_HTML),
        Err(LoginErr::NoEntropy) => json(scratch, |w| w.raw("{\"error\":\"entropy source unavailable, try again\"}")).with_status(503),
        Err(LoginErr::Throttled) => json(scratch, |w| w.raw("{\"error\":\"too many attempts, wait a minute\"}")).with_status(429),
        Err(LoginErr::BadToken) => Response { status: 303, ctype: "text/plain", body: Body::Scratch(0), location: Some("/login"), set_cookie: None },
    }
}

impl Response {
    fn page(status: u16, html: &'static [u8]) -> Self {
        Response { status, ctype: "text/html; charset=utf-8", body: Body::Static(html), location: None, set_cookie: None }
    }

    fn with_status(mut self, s: u16) -> Self {
        self.status = s;
        self
    }

    pub fn body_len(&self) -> Option<usize> {
        match self.body {
            Body::Static(b) => Some(b.len()),
            Body::Scratch(n) => Some(n),
            Body::Sse => None,
        }
    }
}

fn reason(status: u16) -> &'static str {
    match status {
        200 => "OK",
        302 => "Found",
        303 => "See Other",
        401 => "Unauthorized",
        403 => "Forbidden",
        429 => "Too Many Requests",
        503 => "Service Unavailable",
        400 => "Bad Request",
        404 => "Not Found",
        405 => "Method Not Allowed",
        _ => "Internal Server Error",
    }
}

/// Write the status line + headers for `resp` into `out`; returns the length.
pub fn write_head(resp: &Response, out: &mut [u8]) -> usize {
    write_head_tls(resp, out, false)
}

/// `write_head` for a response travelling over TLS: the session cookie gains `Secure` (ADR 0051 D4).
pub fn write_head_tls(resp: &Response, out: &mut [u8], secure: bool) -> usize {
    write_head_ka(resp, out, secure, false)
}

/// Idle seconds a kept-alive connection may wait for its next request, and requests per connection.
pub const KEEPALIVE_SECS: u64 = 15;
pub const KEEPALIVE_MAX: u16 = 100;

/// `write_head_tls` that keeps the connection open after a sized body when `keep` (HTTP keep-alive):
/// the next request reuses the TCP connection — and, over HTTPS, the TLS session.
pub fn write_head_ka(resp: &Response, out: &mut [u8], secure: bool, keep: bool) -> usize {
    use core::fmt::Write;
    let mut w = JsonBuf::new(out);
    // No CORS header: the UI is same-origin (served by this device), and the session cookie must
    // never be usable cross-origin.
    let _ = write!(w, "HTTP/1.1 {} {}\r\nContent-Type: {}\r\nServer: heqk\r\nX-Content-Type-Options: nosniff\r\nX-Frame-Options: DENY\r\n",
        resp.status, reason(resp.status), resp.ctype);
    if let Some(l) = resp.location {
        let _ = write!(w, "Location: {}\r\n", l);
    }
    if let Some(c) = resp.set_cookie {
        if c == CLEAR_COOKIE {
            // logout: expire the cookie in the browser too
            let _ = write!(w, "Set-Cookie: {}=; HttpOnly; SameSite=Strict; Path=/; Max-Age=0{}\r\n", mcauth::COOKIE, if secure { "; Secure" } else { "" });
        } else {
            let _ = write!(w, "Set-Cookie: {}={}; HttpOnly; SameSite=Strict; Path=/; Max-Age=43200{}\r\n",
                mcauth::COOKIE, core::str::from_utf8(&c).unwrap_or(""), if secure { "; Secure" } else { "" });
        }
    }
    match resp.body_len() {
        Some(n) => {
            if keep {
                let _ = write!(w, "Content-Length: {}\r\nCache-Control: no-store\r\nConnection: keep-alive\r\nKeep-Alive: timeout={}, max={}\r\n\r\n", n, KEEPALIVE_SECS, KEEPALIVE_MAX);
            } else {
                let _ = write!(w, "Content-Length: {}\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n", n);
            }
        }
        None => w.raw("Cache-Control: no-cache\r\nConnection: keep-alive\r\n\r\n"),
    }
    w.len
}

