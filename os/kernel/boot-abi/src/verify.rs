//! The ONE hybrid secure-boot verifier + the ONE embedded trust root.
//!
//! This is the single code path that decides whether a HEQK payload is
//! authentic and not rolled back. It is called from TWO places, and only two:
//!   * **HBoot** (`hboot/src/main.rs`) — the AUTHORITATIVE boot-time verify, run
//!     on the image the firmware is about to launch at EL1 (metal).
//!   * **The kernel's M3.4 OTA orchestrator** (`kernel/src/ota.rs`) — the
//!     on-device pre-flight verify, run on a candidate BEFORE it is staged to the
//!     inactive slot and BEFORE the tryboot flip. Belt-and-suspenders: HBoot will
//!     re-verify the candidate at its trial boot, so this pre-flight only refuses
//!     to *waste* a trial cycle on (or stage a downgrade of) an image HBoot would
//!     reject anyway.
//!
//! Both call sites share:
//!   * the SAME trust root — [`TRUSTED_ED25519_PUBKEY`] + [`TRUSTED_SLHDSA_PUBKEY`]
//!     (defined here, re-exported by `hboot::trusted_keys`),
//!   * the SAME signed message — `SHA-256( LE64(svn) || sha256(payload) )` via
//!     [`crate::signed_message_input`] then a final SHA-256,
//!   * the SAME requirement — BOTH signatures verify AND `svn >= floor`.
//! There is deliberately no second verifier and no second key set.

use crate::sha256;
use crate::{
    signed_message_input, PayloadHeader, ED25519_SIG_LEN, KERNEL_LOAD_PA, PAYLOAD_MAGIC, SIG_CTX,
    SLHDSA_SIG_LEN,
};
use ed25519_compact::{PublicKey as EdPublicKey, Signature as EdSignature};
use fips205::slh_dsa_sha2_128s;
use fips205::traits::{SerDes, Verifier};

/// HBoot's embedded ed25519 root of trust (classical half of the hybrid pair).
/// GENERATED by `heqk-sign keygen`; the private half never leaves the signer.
/// The public keys live in the verifier, never in the signed image (else an
/// attacker could swap key + signature together).
pub const TRUSTED_ED25519_PUBKEY: [u8; 32] = [
    0xa5, 0x8a, 0x32, 0x92, 0x50, 0x70, 0x64, 0xb3, 0xb3, 0x42, 0x69, 0xd7, 0x3d, 0x4b, 0x4a, 0xe5,
    0xc8, 0x9d, 0x81, 0x0a, 0x8b, 0x67, 0x40, 0x03, 0x47, 0x8a, 0xd5, 0x76, 0x55, 0x9f, 0xad, 0x9c,
];

/// HBoot's embedded SLH-DSA-SHA2-128s (FIPS 205) root of trust (post-quantum
/// half). Breaking boot requires forging BOTH this AND the classical signature.
pub const TRUSTED_SLHDSA_PUBKEY: [u8; 32] = [
    0x8c, 0x25, 0xa2, 0xd7, 0x30, 0x9a, 0xec, 0xbe, 0x7b, 0x8b, 0x3a, 0x10, 0x38, 0xea, 0x6f, 0x35,
    0xd0, 0x6d, 0xfb, 0x7b, 0xc0, 0x32, 0x5c, 0x1e, 0x46, 0x7c, 0x78, 0x06, 0x9c, 0xd0, 0xf7, 0x7f,
];

/// The 32-byte message both signatures cover: `SHA-256( LE64(svn) || sha256(payload) )`.
/// Binding the SVN INSIDE the signed message is what makes anti-rollback sound —
/// an attacker cannot raise the version on an old payload without invalidating
/// both signatures. Signer (heqk-sign), HBoot, and the OTA pre-flight all compute
/// this identically.
#[inline]
pub fn digest_signed(svn: u64, payload_hash: &[u8; 32]) -> [u8; 32] {
    sha256::digest(&signed_message_input(svn, payload_hash))
}

/// Verify the classical ed25519 signature over `signed` against the embedded
/// trust root. Fail-closed: any malformed key/signature is `false`.
#[inline]
pub fn verify_ed25519(signed: &[u8; 32], sig: &[u8; ED25519_SIG_LEN]) -> bool {
    (|| {
        let pk = EdPublicKey::from_slice(&TRUSTED_ED25519_PUBKEY).ok()?;
        let s = EdSignature::from_slice(sig).ok()?;
        pk.verify(signed, &s).ok()
    })()
    .is_some()
}

/// Verify the post-quantum SLH-DSA-SHA2-128s signature over `signed` against the
/// embedded trust root. Fail-closed on a malformed key.
#[inline]
pub fn verify_slhdsa(signed: &[u8; 32], sig: &[u8; SLHDSA_SIG_LEN]) -> bool {
    match slh_dsa_sha2_128s::PublicKey::try_from_bytes(&TRUSTED_SLHDSA_PUBKEY) {
        Ok(pk) => pk.verify(signed, sig, SIG_CTX),
        Err(_) => false,
    }
}

/// Why a candidate was refused. Distinct variants so the OTA log and HBoot can
/// name the exact reason (and so a test can assert the precise refusal).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VerifyErr {
    /// Header magic is not `PAYLOAD_MAGIC` — not a HEQK payload.
    BadMagic,
    /// Insane payload size (0 or past the ~2 MiB the EEPROM loads).
    BadSize,
    /// Load geometry not pinned to the fixed values every legitimate image uses.
    BadGeometry,
    /// The declared `size` overruns the buffer we were handed.
    Truncated,
    /// Classical ed25519 signature did not verify.
    BadEd25519,
    /// Post-quantum SLH-DSA signature did not verify.
    BadSlhDsa,
    /// Validly signed, but `svn < floor` — an anti-rollback (downgrade) refusal.
    BelowFloor,
}

/// The outcome of a passing verify: the version and the recomputed measurement.
#[derive(Debug, Clone, Copy)]
pub struct Verified {
    /// Security version number of the accepted payload (== `hdr.svn`, and it is
    /// bound into both signatures, so this value is trustworthy).
    pub svn: u64,
    /// SHA-256 the verifier recomputed over the payload body (NOT the header's
    /// stored copy) — the measured identity.
    pub hash: [u8; 32],
}

/// Verify a candidate payload the SAME way HBoot verifies a boot image:
///  1. header magic + size/geometry sanity (matches HBoot's pre-verify gates),
///  2. recompute SHA-256 over the body (bind to the recompute, never the stored
///     hash — a tampered body fails even if the attacker rewrites `hdr.sha256`),
///  3. require BOTH the ed25519 AND the SLH-DSA signature over the signed message,
///  4. require `svn >= floor` (anti-rollback).
///
/// `body` is the payload bytes the header describes (`hdr.size` of them must be
/// present). `floor` is the caller's effective anti-rollback floor
/// (`rollback::effective_floor()` on metal; the compile floor in QEMU).
pub fn verify_payload(hdr: &PayloadHeader, body: &[u8], floor: u64) -> Result<Verified, VerifyErr> {
    if hdr.magic != PAYLOAD_MAGIC {
        return Err(VerifyErr::BadMagic);
    }
    if hdr.size == 0 || hdr.size > 0x20_0000 {
        return Err(VerifyErr::BadSize);
    }
    // Geometry is constant in this design; a deviation means a redirected copy /
    // jump-to-unsigned-bytes attempt. Pin both, exactly as HBoot does.
    if hdr.load_pa != KERNEL_LOAD_PA as u64 || hdr.entry_offset != 0 || hdr.entry_offset >= hdr.size
    {
        return Err(VerifyErr::BadGeometry);
    }
    let size = hdr.size as usize;
    if body.len() < size {
        return Err(VerifyErr::Truncated);
    }
    let computed = sha256::digest(&body[..size]);
    let signed = digest_signed(hdr.svn, &computed);
    if !verify_ed25519(&signed, &hdr.ed25519_sig) {
        return Err(VerifyErr::BadEd25519);
    }
    if !verify_slhdsa(&signed, &hdr.slhdsa_sig) {
        return Err(VerifyErr::BadSlhDsa);
    }
    if hdr.svn < floor {
        return Err(VerifyErr::BelowFloor);
    }
    Ok(Verified {
        svn: hdr.svn,
        hash: computed,
    })
}
