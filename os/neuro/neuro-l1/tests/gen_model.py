"""Generate src/s1_model.rs from tools/neuro-research/models/s1/s1_model.json (the frozen M3 S1 integer twin).
Usage: python3 -I gen_model.py   (writes ../src/s1_model.rs; deterministic)"""
import hashlib, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
P = os.path.join(HERE, "..", "..", "..", "..", "tools", "neuro-research", "models", "s1", "s1_model.json")
raw = open(P, "rb").read(); M = json.loads(raw); I = M["integer"]
ORDER = ["log_flows", "out_frac", "log_remotes", "log_dst_ports", "port_entropy", "top_port_share", "fail_ratio",
         "log_bytes_out", "log_bytes_in", "log_out_in_ratio", "log_mean_dur", "log_pkts_per_flow", "tcp_frac", "udp_frac",
         "icmp_frac", "wellknown_frac", "telnet_frac", "ssh_frac", "smb_frac", "web_frac", "dns_frac", "ntp_frac",
         "periodic_cv", "log_period_s", "log_max_per_min", "novel_pair_frac", "lan_peer_frac", "log_inbound_sources"]
assert M["features"] == ORDER, M["features"]
q32 = lambda v: int(round(v * 2 ** 32))
out = ["// SPDX-License-Identifier: AGPL-3.0-only",
       "// GENERATED by tests/gen_model.py from tools/neuro-research/models/s1/s1_model.json - do not edit.",
       "// s1_model.json sha256 %s" % hashlib.sha256(raw).hexdigest(),
       "//! The frozen M3 S1 model's integer twin (doc 31 / doc 35 §4): u8 features, i16 weights, i32 accumulator.",
       "",
       "/// SHA-256 of the s1_model.json this table was generated from.",
       "pub const MODEL_SHA256: &str = \"%s\";" % hashlib.sha256(raw).hexdigest(),
       "/// Per-feature quantisation origin, Q32 fixed point.",
       "pub const LO_Q32: [i64; 28] = [%s];" % ", ".join(str(q32(v)) for v in I["lo"]),
       "/// Per-feature quantisation range, Q32 fixed point (> 0).",
       "pub const RANGE_Q32: [i64; 28] = [%s];" % ", ".join(str(q32(v)) for v in I["range"]),
       "/// Weight per u8 quantum.",
       "pub const WQ: [i16; 28] = [%s];" % ", ".join(str(v) for v in I["wq_i16"]),
       "pub const BQ: i32 = %d;" % I["bq_i32"],
       "/// Alert iff accumulator > THR_Q.",
       "pub const THR_Q: i32 = %d;" % I["thr_q_i32"]]
# doc 53 R10: the dev= token tables come from tools/neuro-research/dev_token.py (one formula, no copy here)
import sys
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "tools", "neuro-research"))
import dev_token  # noqa: E402
out += ["/// dev= token (doc 53 R10): z_q16 = DEV_A_Q16 + DEV_B_Q16 * q, the S1 standardisation on the dequantised feature.",
        "pub const DEV_A_Q16: [i32; 28] = [%s];" % ", ".join(str(v) for v in dev_token.A_Q16),
        "pub const DEV_B_Q16: [i32; 28] = [%s];" % ", ".join(str(v) for v in dev_token.B_Q16),
        "/// Short feature names for the token, in feature order.",
        "pub const DEV_NAMES: [&str; 28] = [%s];" % ", ".join('"%s"' % n for n in dev_token.NAMES), ""]
open(os.path.join(HERE, "..", "src", "s1_model.rs"), "w").write("\n".join(out))
print("ok", hashlib.sha256(raw).hexdigest())
