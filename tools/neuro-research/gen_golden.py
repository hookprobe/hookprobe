"""Generate the bit-exact conformance vectors for the Rust engine (os/neuro/neuro-core) from the integer
reference (dna_fixed.py), and the Rust source of the log2 table.

Writes:
  <out>/tests/golden.txt     line format (one token per field, hex for 32/64-bit values):
      S <x hex> <splitmix64(x) hex>          hash checks
      L <x> <log2_q8(x)>                     log2 checks
      P <ip hex> <port> <fingerprint hex>    fingerprint checks
      R <dev>                                reset device <dev> (fresh state)
      F <dev> <fp hex> <bytes> <conns>       flow event
      N <dev> <fp hex>                       flow event with no peer (bytes/conns only): bytes conns follow
      D <dev> <fp hex> <nx 0|1>              DNS event
      C <dev> <hr> <score> <vol> <fan> <novel> <dns> <act>   close hour; expected Q8 results
      X <dev> <act0..23> | <bmu..> | ...     final profile dump (checked at the end)
  <out>/src/log2_lut.rs   the 256-entry Q8 table, generated so Rust and Python cannot drift

Deterministic (seeded). Usage: python3 -I gen_golden.py <os/neuro/neuro-core>
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dna_fixed as fx  # noqa: E402


def main():
    out = sys.argv[1]
    os.makedirs(os.path.join(out, "tests"), exist_ok=True)
    os.makedirs(os.path.join(out, "src"), exist_ok=True)
    with open(os.path.join(out, "src", "log2_lut.rs"), "w") as f:
        f.write("// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by tools/neuro-research/gen_golden.py -- do not edit.\n")
        f.write("/// round(log2(1 + i/256) * 256), i = 0..255 (Q8).\npub const LOG2_LUT: [u16; 256] = [\n")
        for i in range(0, 256, 16):
            f.write("    " + ", ".join(str(v) for v in fx.LOG2_LUT[i:i + 16]) + ",\n")
        f.write("];\n")

    r = random.Random(20261118)
    L = []
    for x in [0, 1, 2, 0x9E3779B97F4A7C15, 0xFFFFFFFFFFFFFFFF, 123456789]:
        L.append("S %x %x" % (x, fx.splitmix64(x)))
    for x in [1, 2, 3, 4, 5, 255, 256, 257, 1000, 65535, 65536, 123456789, 2 ** 40 + 12345, 2 ** 63 + 7]:
        L.append("L %d %d" % (x, fx.log2_q8(x)))
    for ip, port in [(0xC0A8010A, 443), (0xCB007158, 4444), (0, 0), (0xFFFFFFFF, 65535)]:
        L.append("P %x %d %x" % (ip, port, fx.fingerprint(fx.peer_key(ip, port))))

    # Three devices with different habits, 400 hours each (crosses two Bloom rotations at 168 and 336),
    # with injected scans, exfiltration, new services, DGA bursts and a benign drift.
    kinds = [("camera", 2, 30, 40_000, 2, range(0, 24)), ("laptop", 40, 120, 8_000, 30, range(8, 19)),
             ("plug", 1, 4, 500, 1, range(0, 24))]
    for dev, (name, npeers, base, bpc, nsuf, peak) in enumerate(kinds):
        L.append("R %d" % dev)
        dna, agg = fx.DNAFixed(), fx.HourAgg()
        peers = [(r.getrandbits(32), r.choice([443, 80, 8883, 123])) for _ in range(npeers)]
        sufs = [r.getrandbits(64) for _ in range(nsuf)]
        for h in range(400):
            hr = h % 24
            on = hr in peak
            conns = int(base * (1.0 if on else 0.15) * r.uniform(0.6, 1.4))
            if h == 300 and dev == 1:
                peers += [(0xCB000000 | q, 443) for q in range(5)]          # benign drift: a new SaaS app
            k = min(len(peers), max(1, int((conns + 1) ** 0.5))) if conns else 0
            chosen = r.sample(peers, k)
            inj = None
            if h in (250, 251) and dev == 0:
                inj = "scan"
            elif h == 260 and dev == 2:
                inj = "exfil"
            elif h in range(270, 274) and dev == 1:
                inj = "dga"
            elif h in range(280, 284) and dev == 2:
                inj = "new_service"
            per = max(1, conns // max(1, k)) if k else 0
            for j, (ip, port) in enumerate(chosen):
                b = per * bpc * r.randint(50, 150) // 100
                if inj == "exfil" and j == 0:
                    b += 2_000_000_000
                fp = fx.fingerprint(fx.peer_key(ip, port))
                agg.add_flow(dna, fp, b, per)
                L.append("F %d %x %d %d" % (dev, fp, b, per))
            if not chosen and conns:
                agg.add_flow(dna, None, conns * bpc, conns)
                L.append("N %d %d %d" % (dev, conns * bpc, conns))
            if inj == "scan":
                for q in range(1, 60):
                    for port in (22, 445):
                        fp = fx.fingerprint(fx.peer_key(0xC0A80A00 | q, port))
                        agg.add_flow(dna, fp, 60, 1)
                        L.append("F %d %x 60 1" % (dev, fp))
            if inj == "new_service":
                fp = fx.fingerprint(fx.peer_key(0xCB007101, 4444))
                agg.add_flow(dna, fp, 5000, 15)
                L.append("F %d %x 5000 15" % (dev, fp))
            nq = max(1, conns // 10) if conns else 0
            for _ in range(nq):
                s = r.choice(sufs)
                fp = fx.fingerprint(s)
                nx = 1 if r.random() < 0.02 else 0
                agg.add_dns(dna, fp, nx)
                L.append("D %d %x %d" % (dev, fp, nx))
            if inj == "dga":
                for _ in range(150):
                    fp = fx.fingerprint(r.getrandbits(64))
                    agg.add_dns(dna, fp, 1)
                    L.append("D %d %x 1" % (dev, fp))
            s, p = dna.close_hour(hr, agg)
            L.append("C %d %d %d %d %d %d %d %d" % (dev, hr, s, p["vol"], p["fan"], p["novel"], p["dns"], p["act"]))
            agg.reset()
        L.append("X %d %s | %s | %s | %s | %s | %s | %s %s %s %s" % (
            dev, " ".join(map(str, dna.act)), " ".join(map(str, dna.bmu)), " ".join(map(str, dna.bdev)),
            " ".join(map(str, dna.fmu)), " ".join(map(str, dna.fdev)), " ".join(map(str, dna.n)),
            dna.nx, dna.nov_mu, dna.nov_dev, " ".join(map(str, dna.p))))
    with open(os.path.join(out, "tests", "golden.txt"), "w") as f:
        f.write("\n".join(L) + "\n")
    alarms = sum(1 for l in L if l.startswith("C ") and int(l.split()[3]) >= fx.CALM_Q8)
    print("wrote %d lines (%d hour closes, %d alarming) and src/log2_lut.rs" % (
        len(L), sum(1 for l in L if l.startswith("C ")), alarms))


if __name__ == "__main__":
    main()
