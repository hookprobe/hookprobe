"""Regenerate samples/ from the test fixtures (reserved IP/domain values only, no real data).

  python3 -I make_samples.py
"""
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "tests"))
sys.path.insert(0, HERE)

from helpers import FIX, FIXTURE_FILES, Sandbox  # noqa: E402
from heqkdata import canon, export, normalize, registry  # noqa: E402
from heqkdata.store import Store  # noqa: E402


def main():
    sb = Sandbox()
    try:
        reg, st = registry.Registry(sb.reg), Store(sb.data)
        for sid, rel in FIXTURE_FILES.items():
            acq = st.register(reg, sid, os.path.join(FIX, rel), "research" if sid == "f-cic" else "live_intel")
            normalize.normalize(st, reg, acq)
        out = os.path.join(HERE, "samples")
        shutil.rmtree(out, ignore_errors=True)
        os.makedirs(out)
        recs = list(st.records())
        with open(os.path.join(out, "security-events.jsonl"), "w", encoding="utf-8") as f:
            for kind in ("dns", "flow", "indicator", "vulnerability", "attack_technique"):
                r = next(x for x in recs if x["kind"] == kind)
                f.write(canon.canonical_json(r) + "\n")
        bdir, man, _ = export.build(st, reg, "research", out_root=os.path.join(sb.dir, "b"))
        with open(os.path.join(out, "training-examples.jsonl"), "w", encoding="utf-8") as f, \
                open(os.path.join(out, "sft-chat.jsonl"), "w", encoding="utf-8") as g:
            for o in man["outputs"]:
                if o["path"].startswith("examples/"):
                    with open(os.path.join(bdir, o["path"]), encoding="utf-8") as src:
                        e = json.loads(src.readline())
                    f.write(canon.canonical_json(e) + "\n")
                    g.write(canon.canonical_json(export.to_chat(e)) + "\n")
        shutil.copy(os.path.join(bdir, "QUALITY.md"), os.path.join(out, "QUALITY-fixtures.md"))
        with open(os.path.join(out, "README.md"), "w", encoding="utf-8") as f:
            f.write("# samples\n\nGENERATED by `python3 -I make_samples.py` from `tests/fixtures/` (RFC 5737 / RFC 2606 "
                    "values, fictitious CVE-2099-* ids). Illustrative of the formats only: not real telemetry, not threat "
                    "intelligence. Source ids starting `f-` are fixture sources.\n")
        print(f"samples written to {out}")
    finally:
        sb.close()


if __name__ == "__main__":
    main()
