//! Inspection substrate — multi-mode, self-selecting traffic capture + detection. "Everything is
//! rogue": every forwarding interface is inspected by the local SOC, in BOTH directions, on the
//! WAN side AND the LAN side (cover all round). The enforcement/observation PLANE is picked per-NIC
//! from capability (the "capabilities, not branches" law the fabric follows):
//!
//! ```text
//! Per-NIC mode ladder (best → floor):
//!   1. xdp-native — driver XDP hook: in-kernel per-packet + inline XDP_DROP     [driver supports it]
//!   2. tc-bpf     — SCHED_CLS at the clsact hook: in-kernel, near-universal      [any NIC, incl. Wi-Fi]
//!   3. software   — userspace conntrack-flow floor (senzorium-flow)              [pre-5.19 / no-BPF]
//! ```
//!
//! Corrected from an earlier `xdp-native > xdp-generic > software` ladder: **generic/skb-XDP is a
//! non-production shim** (runs after skb alloc, none of native XDP's speed), so the real fallback is
//! **TC-bpf** (`BPF_PROG_TYPE_SCHED_CLS` at `clsact` ingress/egress) — a first-class in-kernel hook.
//! Critically, **Wi-Fi (mac80211/brcmfmac) has NO native XDP**, so a Pi AP's `wlan0` uses TC-bpf,
//! which sees post-802.11-decap Ethernet frames — a standard parser works. See docs/adr/0004.
//!
//! One detection core (CO-RE `.bpf.o`) is compiled once and attached as either an XDP or a
//! SCHED_CLS program by the loader, per the NIC's probed capability. Stateful decisions use the
//! `bpf_{skb,xdp}_ct_lookup` kfuncs (kernel ≥ 5.19, nf_conntrack loaded): established flows fast-pass
//! in-kernel, new/suspicious escalate to userspace NAPSE — replacing the userspace `/proc` read.
//!
//! COVER ALL ROUND — each NIC is tagged [`InspectRole`]: the WAN uplink gets ingress-threat policy
//! (RPF anti-spoof, SYN-flood, threat-feed blocklist, inbound scans) + egress exfil/C2 detection;
//! LAN/AP NICs get client policy (lateral movement, rogue/compromised devices, DNS tunneling, NAC).
//! The same core runs on both; the role selects the ruleset. Plus a tc-mirred copy of every NIC to
//! the DPI sink, so full-packet inspection covers both sides regardless of the fast-path mode.

use crate::multi_wan::GeneratedFile;
use crate::types::{InterfaceType, ManifestInterface};

const BANNER: &str = "# GENERATED by hookprobe AEGIS (inspect reconciler) — do not edit by hand.\n";

/// The in-kernel/ userspace capture mode for one interface. XDP-first with a TC-bpf fallback that
/// works on any NIC (including Wi-Fi), and a userspace floor for pre-5.19 / BTF-less kernels.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CaptureMode {
    /// Driver (native) XDP — fastest, in-kernel, pre-stack, inline XDP_DROP.
    XdpNative,
    /// TC-bpf (`SCHED_CLS` at `clsact`) — in-kernel, universal (Wi-Fi/virtio/legacy), inline drop.
    TcBpf,
    /// Userspace conntrack-flow floor (senzorium-flow). No eBPF needed. Pre-5.19 / no-BTF fallback.
    Software,
}

impl CaptureMode {
    pub fn as_str(self) -> &'static str {
        match self {
            CaptureMode::XdpNative => "xdp-native",
            CaptureMode::TcBpf => "tc-bpf",
            CaptureMode::Software => "software",
        }
    }
}

/// Which side of the router a NIC sits on — selects the detection ruleset (cover all round).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InspectRole {
    /// Uplink (WAN/dongle/cellular): ingress threats (RPF, SYN-flood, blocklist, scans) + egress exfil/C2.
    Wan,
    /// LAN/AP carrier: client behaviour (lateral movement, rogue/compromised devices, DNS tunnel, NAC).
    Lan,
}

impl InspectRole {
    pub fn as_str(self) -> &'static str {
        match self {
            InspectRole::Wan => "wan",
            InspectRole::Lan => "lan",
        }
    }
}

/// Per-NIC XDP capability facts (bootstrap probes these ONCE → manifest). Absent today ⇒ the ladder
/// uses TC-bpf; the day a driver gains native XDP the flag flips and the fast path upgrades.
#[derive(Debug, Clone, Copy, Default)]
pub struct XdpCaps {
    pub native: bool,
}

/// Pick the best capture mode for a NIC. `bpf_stateful` = the host kernel is ≥ 5.19 with BPF +
/// nf_conntrack (so SCHED_CLS + `bpf_ct_lookup` are usable). XDP-first; TC-bpf is the real fallback
/// (never generic/skb XDP); the userspace floor only when the kernel can't run our BPF at all.
pub fn select_mode(caps: XdpCaps, bpf_stateful: bool) -> CaptureMode {
    if !bpf_stateful {
        CaptureMode::Software
    } else if caps.native {
        CaptureMode::XdpNative
    } else {
        CaptureMode::TcBpf
    }
}

/// Operator inspection intent. Defaults are the zero-trust posture: mirror everything, DPI on.
/// `#[serde(default)]` so an empty `inspect: {}` in network.yaml yields the full zero-trust posture.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(default)]
pub struct InspectIntent {
    /// The mirror sink interface (V1's `dummy-mirror`). A DPI sensor reads from it.
    pub mirror_sink: String,
    /// Mirror all forwarding interfaces to the sink for full-packet DPI ("everything is rogue").
    pub mirror: bool,
    /// Prefer inline enforcement where the NIC supports drop (else observe-only + reactive nft).
    pub inline_enforce: bool,
    /// Trigger-to-evidence pcap capture (roadmap D): `napse-dpi`'s bounded per-source ring +
    /// bounded post-trigger tail, written to `/var/lib/hookprobe/pcap/` and linked into the
    /// evidence graph (`crates/hookprobe-evidence`'s `pcaps` table + `detection_to_pcap` edge) —
    /// see `napse_loader::capture`'s module doc for the full design. Default ON: this is an IDS,
    /// and the capture itself is tightly bounded on BOTH ends (a small in-memory ring ceiling here
    /// via `capture_cap_mb`, and ADR 0003's 8 GB/~24h on-disk directory retention enforced by
    /// `hookprobe-evidence-prune.timer`, independent of this flag) — an operator who wants zero
    /// pcap-writing overhead (e.g. a storage-constrained edge device) sets this `false`.
    #[serde(default = "default_capture")]
    pub capture: bool,
    /// Both the pre-trigger ring lookback AND the post-trigger tail duration
    /// (`napse_loader::capture::CaptureConfig::window_secs`) — a captured detection's total span
    /// is bounded by roughly `2 * capture_window_secs`. `#[serde(default)]` (0.0) with the real
    /// default resolved by `napse-dpi` itself (`capture::DEFAULT_CAPTURE_WINDOW_SECS`) when unset
    /// — mirrors how `mirror_sink`/`mirror` are resolved (network.yaml declares intent; the
    /// consuming binary owns its own numeric defaults), so this struct never needs to duplicate a
    /// magic number that could drift from the one `napse-dpi` actually uses.
    pub capture_window_secs: f64,
    /// In-memory (per `napse-dpi` PROCESS) capture ring ceiling, megabytes
    /// (`napse_loader::capture::CaptureConfig::global_max_bytes`). `0` (the `#[serde(default)]`
    /// value) means "use napse-dpi's own default" (`capture::DEFAULT_CAPTURE_CAP_MB`) — same
    /// resolve-in-the-consumer discipline as `capture_window_secs`. NOT the same number as ADR
    /// 0003's on-disk directory retention cap (`hookprobe_evidence::PCAP_DIR_CAP_BYTES`, gigabytes)
    /// — this is the much smaller live-memory bound.
    pub capture_cap_mb: u32,
}

fn default_capture() -> bool {
    true
}

impl Default for InspectIntent {
    fn default() -> Self {
        Self {
            mirror_sink: "hp-mirror".to_string(),
            mirror: true,
            inline_enforce: false,
            capture: true,
            capture_window_secs: 0.0,
            capture_cap_mb: 0,
        }
    }
}

/// One interface's resolved inspection posture: capture mode + WAN/LAN policy side + mirrored?.
#[derive(Debug, Clone)]
pub struct IfaceInspect {
    pub iface: String,
    pub mode: CaptureMode,
    pub role: InspectRole,
    pub mirrored: bool,
}

/// The resolved inspection plan.
#[derive(Debug, Clone)]
pub struct InspectPlan {
    pub ifaces: Vec<IfaceInspect>,
    pub artifacts: Vec<GeneratedFile>,
    pub summary: String,
}

/// Wired + Wi-Fi NICs can be tc-mirred (the DPI feed). Cellular (WWAN) usually can't, so it is
/// inspected for POLICY (eBPF TC attach) but mirror-exempt.
fn is_mirrorable(i: &ManifestInterface) -> bool {
    matches!(i.iface_type, InterfaceType::Ethernet | InterfaceType::Wifi)
}

/// A NIC is inspected iff it bears user traffic: any wired/Wi-Fi port, OR a cellular UPLINK — a WAN
/// we must still police (RPF/SYN-flood/blocklist) even though we can't mirror it. Never the sink.
/// "Everything is rogue" — no allowlist.
fn is_inspect_target(i: &ManifestInterface, sink: &str, uplinks: &[&str]) -> bool {
    if i.name == sink {
        return false;
    }
    is_mirrorable(i)
        || (matches!(i.iface_type, InterfaceType::Lte) && uplinks.contains(&i.name.as_str()))
}

/// Build the inspection plan: for every traffic-bearing NIC pick the fast-path mode (XDP where the
/// driver supports it, else TC-bpf, else the software floor), tag its WAN/LAN policy side, and — when
/// `mirror` is set — tc-mirred it to the sink for full-packet DPI. Covers both sides (WAN + LAN).
///
/// `wan_uplink` is the primary uplink (tagged WAN; everything else is LAN). `xdp_caps_for` supplies
/// per-NIC XDP facts from the manifest; `bpf_stateful` = kernel ≥ 5.19 + nf_conntrack (the ct-lookup
/// fast-path seam). Both default conservatively today (⇒ software / no-native) and light up as the
/// bootstrap probe fills them in.
pub fn plan(
    interfaces: &[ManifestInterface],
    wan_uplinks: &[&str],
    intent: &InspectIntent,
    xdp_caps_for: impl Fn(&str) -> XdpCaps,
    bpf_stateful: bool,
) -> InspectPlan {
    let targets: Vec<&ManifestInterface> = interfaces
        .iter()
        .filter(|i| is_inspect_target(i, &intent.mirror_sink, wan_uplinks))
        .collect();

    let mut ifaces = Vec::new();
    for i in &targets {
        // EVERY uplink (primary + failover + cellular) is WAN-side, not just the first wired one.
        let role = if wan_uplinks.contains(&i.name.as_str()) { InspectRole::Wan } else { InspectRole::Lan };
        ifaces.push(IfaceInspect {
            iface: i.name.clone(),
            mode: select_mode(xdp_caps_for(&i.name), bpf_stateful),
            role,
            mirrored: intent.mirror && is_mirrorable(i),
        });
    }

    let mut artifacts = Vec::new();
    // Mirror only the mirror-capable (wired/Wi-Fi) subset; cellular is policed by eBPF, not mirrored.
    let mirror_names: Vec<&str> = targets.iter().filter(|i| is_mirrorable(i)).map(|i| i.name.as_str()).collect();
    if intent.mirror && !mirror_names.is_empty() {
        artifacts.push(render_mirror(&intent.mirror_sink, &mirror_names));
    }
    // Trigger-to-evidence pcap capture (roadmap D): translate the operator's `capture`/
    // `capture_window_secs`/`capture_cap_mb` intent into the SAME env-var names `napse-dpi`'s
    // `capture_config_from_env` already reads. Always emitted (unlike the mirror artifact above,
    // which is conditional on `mirror`) so a `false` `capture` still lands as an explicit
    // `NAPSE_CAPTURE_ENABLED=0`, not silence. NOTE (honest scope): `napse-dpi.service` does not
    // yet declare `EnvironmentFile=-/var/lib/hookprobe/napse-capture.env` — wiring that one line
    // is out of THIS pass's file ownership (systemd units are owned elsewhere); until it's added,
    // an operator who wants non-default knobs sets the `Environment=` lines directly (same as the
    // unit's own commented-out `NAPSE_PORTSCAN_*` examples today). The artifact is generated and
    // ready either way.
    artifacts.push(render_capture_env(intent));

    let modes: Vec<String> = ifaces
        .iter()
        .map(|f| format!("{}={}/{}{}", f.iface, f.mode.as_str(), f.role.as_str(), if f.mirrored { "+mirror" } else { "" }))
        .collect();
    let summary = if ifaces.is_empty() {
        "no traffic-bearing interfaces to inspect".to_string()
    } else {
        format!("inspect {} → sink {} · {}", ifaces.len(), intent.mirror_sink, modes.join(" "))
    };

    InspectPlan { ifaces, artifacts, summary }
}

/// tc-mirred mirror plan — the XDP-free universal capture (V1 `setup-ids-mirror.sh`, generalized).
/// Creates the dummy sink, then a `clsact` qdisc + `matchall` mirred filter on BOTH ingress and
/// egress of every target NIC → copies every packet to the sink. Out-of-band (a dummy never
/// transmits, never congests), zero latency on the real path. A DPI sensor (AF_PACKET/XDP on the
/// sink) parses DNS/TLS/JA3/HTTP/entropy → the common event schema. Idempotent (`replace`).
/// A Linux interface name is at most 15 chars (IFNAMSIZ-1) and, for anything this crate splices into
/// a root-run shell plan, must be restricted to `[A-Za-z0-9_.-]` — never whitespace, `/`, `;`, `$`,
/// backticks, etc. `mirror_sink` comes from operator-declared `network.yaml` intent (not the probed
/// manifest), so an operator without OS-admin rights must not be able to smuggle shell metacharacters
/// into `ip link add {sink}` / `tc filter … dev {sink}` (ADR 0008 RBAC split; audit MEDIUM).
fn safe_ifname(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 15
        && name != "."
        && name != ".."
        && name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-' || b == b'.')
}

fn render_mirror(raw_sink: &str, ifaces: &[&str]) -> GeneratedFile {
    // Fall back to the compiled default rather than rendering an unvalidated name into a root shell.
    let sink = if safe_ifname(raw_sink) { raw_sink } else { "hp-mirror" };
    let mut s = String::from(BANNER);
    if !safe_ifname(raw_sink) {
        s.push_str(&format!("# NOTE: declared mirror_sink was rejected as an unsafe interface name — using the safe default '{sink}'.\n"));
    }
    s.push_str("# Universal traffic mirror (tc mirred → dummy sink). Works on ANY NIC (no XDP needed):\n");
    s.push_str("# every packet in/out of each forwarding NIC is COPIED to the sink for full DPI.\n");
    s.push_str(&format!(
        "ip link show {sink} >/dev/null 2>&1 || ip link add {sink} type dummy\n\
         ip link set {sink} up 2>/dev/null || true\n\
         ip link set {sink} promisc on 2>/dev/null || true\n"
    ));
    for ifc in ifaces {
        // Pin `pref` + `handle` so `tc filter replace` can IDENTIFY and overwrite the existing filter
        // — without them tc auto-assigns a new priority on every apply and stacks duplicate matchall
        // filters (each packet mirrored N times after N reconciles). ingress/egress are separate
        // clsact hooks, so the same pref/handle on both does not collide.
        s.push_str(&format!(
            "# --- mirror {ifc} (ingress+egress) → {sink} ---\n\
             tc qdisc add dev {ifc} clsact 2>/dev/null || true\n\
             tc filter replace dev {ifc} ingress pref 49152 handle 0x1 matchall action mirred egress mirror dev {sink}\n\
             tc filter replace dev {ifc} egress  pref 49152 handle 0x1 matchall action mirred egress mirror dev {sink}\n"
        ));
    }
    GeneratedFile { path: "fabric/70-mirror.plan".to_string(), content: s }
}

/// Trigger-to-evidence pcap capture (roadmap D) env file — `NAPSE_CAPTURE_*` names matching
/// `napse-dpi.rs`'s `capture_config_from_env` exactly. `0.0`/`0` for
/// `capture_window_secs`/`capture_cap_mb` are omitted (not rendered as `=0`, which would wrongly
/// override `napse_loader::capture::CaptureConfig::default()`'s real, non-zero defaults) — see
/// `InspectIntent`'s doc comment on why those two fields use "0 = let napse-dpi resolve its own
/// default" rather than duplicating a magic number here that could drift from the one napse-dpi
/// actually uses.
fn render_capture_env(intent: &InspectIntent) -> GeneratedFile {
    let mut s = String::from(
        "# GENERATED by hookprobe AEGIS (inspect reconciler) — do not edit by hand.\n\
         # Trigger-to-evidence pcap capture (roadmap D) knobs for napse-dpi. NOT YET loaded by\n\
         # napse-dpi.service (no EnvironmentFile= line there today — see inspect::plan's doc\n\
         # comment); ready for that unit to pick up once wired.\n",
    );
    s.push_str(&format!("NAPSE_CAPTURE_ENABLED={}\n", if intent.capture { 1 } else { 0 }));
    if intent.capture_window_secs > 0.0 {
        s.push_str(&format!("NAPSE_CAPTURE_WINDOW_SECS={}\n", intent.capture_window_secs));
    }
    if intent.capture_cap_mb > 0 {
        s.push_str(&format!("NAPSE_CAPTURE_CAP_MB={}\n", intent.capture_cap_mb));
    }
    GeneratedFile { path: "napse-capture.env".to_string(), content: s }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::{InterfaceRole, InterfaceType};

    fn iface(name: &str, ty: InterfaceType) -> ManifestInterface {
        ManifestInterface {
            name: name.into(), mac: None, iface_type: ty, supported_modes: vec![],
            role: InterfaceRole::Unassigned, fail_mode: None, state: "up".into(), xdp_native: false,
        }
    }

    #[test]
    fn ladder_is_xdp_native_then_tc_bpf_then_software() {
        // Wi-Fi / non-native NIC on a modern kernel → TC-bpf (NOT generic XDP).
        assert_eq!(select_mode(XdpCaps { native: false }, true), CaptureMode::TcBpf);
        // Driver with native XDP → xdp-native.
        assert_eq!(select_mode(XdpCaps { native: true }, true), CaptureMode::XdpNative);
        // Pre-5.19 / no-BPF kernel → userspace software floor regardless of the NIC.
        assert_eq!(select_mode(XdpCaps { native: true }, false), CaptureMode::Software);
    }

    #[test]
    fn covers_wan_and_lan_sides_and_mirrors_all() {
        let ifs = vec![
            iface("end0", InterfaceType::Ethernet),   // WAN uplink
            iface("wlan0", InterfaceType::Wifi),        // LAN/AP
            iface("hp-mirror", InterfaceType::Ethernet),// the sink — must NOT be inspected
            iface("wwan0", InterfaceType::Lte),         // cellular — not tc-mirred here
        ];
        let p = plan(&ifs, &["end0"], &InspectIntent::default(), |_| XdpCaps::default(), true);
        // both real NICs inspected; sink + cellular excluded
        let names: Vec<&str> = p.ifaces.iter().map(|f| f.iface.as_str()).collect();
        assert_eq!(names, vec!["end0", "wlan0"]);
        // cover all round: end0 = WAN policy, wlan0 = LAN policy
        let role = |n: &str| p.ifaces.iter().find(|f| f.iface == n).unwrap().role;
        assert_eq!(role("end0"), InspectRole::Wan);
        assert_eq!(role("wlan0"), InspectRole::Lan);
        // no native XDP known ⇒ both use the TC-bpf tier (Wi-Fi can't do native XDP anyway)
        assert!(p.ifaces.iter().all(|f| f.mode == CaptureMode::TcBpf && f.mirrored));
        // the mirror covers both sides
        let m = p.artifacts.iter().find(|a| a.path.contains("70-mirror.plan")).expect("mirror plan");
        // idempotent: fixed pref/handle so `replace` overwrites rather than stacking duplicates
        assert!(m.content.contains("dev wlan0 ingress pref 49152 handle 0x1 matchall action mirred egress mirror dev hp-mirror"));
        assert!(m.content.contains("dev end0 egress  pref 49152 handle 0x1 matchall action mirred egress mirror dev hp-mirror"));
    }

    #[test]
    fn cellular_and_secondary_uplinks_get_wan_policy() {
        // A cellular-primary + wired-standby failover site. BOTH must be WAN-side (H4 fix): the
        // cellular WAN is policed (eBPF) but mirror-exempt; the standby wired WAN is inspected too.
        let ifs = vec![
            iface("wwan0", InterfaceType::Lte),   // cellular primary
            iface("end0", InterfaceType::Ethernet), // wired standby
            iface("wlan0", InterfaceType::Wifi),  // LAN/AP
        ];
        let p = plan(&ifs, &["wwan0", "end0"], &InspectIntent::default(), |_| XdpCaps::default(), true);
        let f = |n: &str| p.ifaces.iter().find(|x| x.iface == n).expect("target");
        assert_eq!(f("wwan0").role, InspectRole::Wan); // cellular no longer escapes inspection
        assert!(!f("wwan0").mirrored, "cellular is mirror-exempt (can't tc-mirror WWAN)");
        assert_eq!(f("end0").role, InspectRole::Wan); // secondary wired WAN also WAN-policed
        assert_eq!(f("wlan0").role, InspectRole::Lan);
        // the mirror plan covers only the mirror-capable NICs (end0, wlan0), not wwan0
        let m = p.artifacts.iter().find(|a| a.path.contains("70-mirror.plan")).unwrap();
        assert!(!m.content.contains("wwan0"));
        assert!(m.content.contains("dev end0 ingress"));
    }

    #[test]
    fn mirror_can_be_disabled_but_modes_still_resolve() {
        let ifs = vec![iface("end0", InterfaceType::Ethernet)];
        let p = plan(&ifs, &["end0"], &InspectIntent { mirror: false, ..Default::default() }, |_| XdpCaps::default(), true);
        // The mirror plan itself is gone, but the capture-env artifact is ALWAYS emitted
        // (unconditional on `mirror` — see `plan`'s doc comment) — so "no mirror" is exactly one
        // artifact (`napse-capture.env`), not zero.
        assert_eq!(p.artifacts.len(), 1);
        assert!(!p.artifacts.iter().any(|a| a.path.contains("70-mirror.plan")));
        assert!(p.artifacts.iter().any(|a| a.path == "napse-capture.env"));
        assert_eq!(p.ifaces.len(), 1);
        assert_eq!(p.ifaces[0].mode, CaptureMode::TcBpf);
    }

    // ---- Trigger-to-evidence pcap capture (roadmap D): render_capture_env -------------------------

    #[test]
    fn capture_env_defaults_to_enabled_with_no_numeric_overrides() {
        let ifs = vec![iface("end0", InterfaceType::Ethernet)];
        let p = plan(&ifs, &["end0"], &InspectIntent::default(), |_| XdpCaps::default(), true);
        let env = p.artifacts.iter().find(|a| a.path == "napse-capture.env").expect("capture env artifact");
        assert!(env.content.contains("NAPSE_CAPTURE_ENABLED=1"));
        assert!(!env.content.contains("NAPSE_CAPTURE_WINDOW_SECS="), "0.0 (unset) must not render a knob napse-dpi would then treat as an explicit override");
        assert!(!env.content.contains("NAPSE_CAPTURE_CAP_MB="));
    }

    #[test]
    fn capture_env_renders_disabled_explicitly_and_operator_numeric_overrides() {
        let ifs = vec![iface("end0", InterfaceType::Ethernet)];
        let intent = InspectIntent { capture: false, capture_window_secs: 30.0, capture_cap_mb: 64, ..Default::default() };
        let p = plan(&ifs, &["end0"], &intent, |_| XdpCaps::default(), true);
        let env = p.artifacts.iter().find(|a| a.path == "napse-capture.env").unwrap();
        assert!(env.content.contains("NAPSE_CAPTURE_ENABLED=0"), "disabled must render as an explicit 0, never silence");
        assert!(env.content.contains("NAPSE_CAPTURE_WINDOW_SECS=30"));
        assert!(env.content.contains("NAPSE_CAPTURE_CAP_MB=64"));
    }

    #[test]
    fn safe_ifname_rejects_shell_metacharacters_and_overlong_names() {
        assert!(safe_ifname("hp-mirror"));
        assert!(safe_ifname("end0"));
        assert!(safe_ifname("wlan0.1"));
        assert!(!safe_ifname(""));
        assert!(!safe_ifname("this-name-is-way-too-long")); // >15
        assert!(!safe_ifname("a;reboot"));
        assert!(!safe_ifname("$(rm -rf /)"));
        assert!(!safe_ifname("a b"));
        assert!(!safe_ifname("a/../b"));
        assert!(!safe_ifname("`id`"));
    }

    #[test]
    fn render_mirror_falls_back_to_safe_default_on_a_hostile_mirror_sink() {
        // audit MEDIUM: an operator-declared mirror_sink must never smuggle shell metacharacters into
        // the root-run mirror plan. A hostile sink is rejected and the safe default used instead.
        let ifs = vec![iface("end0", InterfaceType::Ethernet)];
        let intent = InspectIntent { mirror_sink: "x; reboot #".to_string(), ..Default::default() };
        let p = plan(&ifs, &["end0"], &intent, |_| XdpCaps::default(), true);
        let mirror = p.artifacts.iter().find(|a| a.path.contains("mirror")).expect("mirror plan");
        assert!(!mirror.content.contains("reboot"), "hostile mirror_sink must not reach the shell plan");
        assert!(mirror.content.contains("hp-mirror"), "must fall back to the safe default sink");
    }
}
