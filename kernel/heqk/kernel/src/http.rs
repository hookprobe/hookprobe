//! Minimal, allocation-free HTTP/1.1 for the on-device Mission Control (ADR 0047 D2).
//!
//! Scope is deliberately small: `GET` only, one request per connection (`Connection: close`),
//! except the SSE stream which stays open. Routes implement the Mission Control UI's contract
//! (the `crates/hookprobe-api` shapes) so the unchanged UI works against a device:
//! `/api/qsecbit`, `/api/incidents`, `/api/detections`, `/api/engines`, `/api/health`,
//! `/api/stream` (SSE `update`), plus the static UI embedded in the image at build time.
//! Pure (no sockets): the serve loop owns TCP; this module turns request bytes into a response.

use crate::mcstate::{JsonBuf, McState};

/// One embedded static file.
pub struct Asset {
    pub path: &'static str,
    pub ctype: &'static str,
    pub body: &'static [u8],
}

// `UI_ASSETS: &[Asset]` — generated by build.rs from `ui/dist` when the `mcserve` feature is on
// (empty otherwise, so non-serving builds carry no UI bytes).
include!(concat!(env!("OUT_DIR"), "/ui_assets.rs"));

#[derive(Debug, PartialEq, Eq)]
pub struct Req<'a> {
    pub get: bool,
    pub path: &'a str,
    pub query: &'a str,
}

#[derive(Debug, PartialEq, Eq)]
pub enum ParseErr {
    /// Headers not complete yet — read more.
    Incomplete,
    /// Not an HTTP/1.x request line (or headers over the cap) — answer 400 and close.
    Bad,
}

/// Parse the request line once the header block (`\r\n\r\n`) is complete. The body (none for
/// GET) and headers are ignored — nothing here depends on them.
pub fn parse(buf: &[u8]) -> Result<Req<'_>, ParseErr> {
    let end = match buf.windows(4).position(|w| w == b"\r\n\r\n") {
        Some(e) => e,
        None => return Err(if buf.len() >= 4096 { ParseErr::Bad } else { ParseErr::Incomplete }),
    };
    let head = core::str::from_utf8(&buf[..end]).map_err(|_| ParseErr::Bad)?;
    let line = head.split("\r\n").next().ok_or(ParseErr::Bad)?;
    let mut parts = line.split(' ');
    let method = parts.next().ok_or(ParseErr::Bad)?;
    let target = parts.next().ok_or(ParseErr::Bad)?;
    let version = parts.next().ok_or(ParseErr::Bad)?;
    if !version.starts_with("HTTP/1.") || !target.starts_with('/') {
        return Err(ParseErr::Bad);
    }
    let (path, query) = match target.find('?') {
        Some(i) => (&target[..i], &target[i + 1..]),
        None => (target, ""),
    };
    Ok(Req { get: method == "GET", path, query })
}

/// `key=<u32>` from a query string.
pub fn query_u32(query: &str, key: &str) -> Option<u32> {
    query.split('&').find_map(|kv| {
        let (k, v) = kv.split_once('=')?;
        if k == key { v.parse().ok() } else { None }
    })
}

/// Map a URL path to an embedded asset: `/` → `index.html`; `/a/b` or `/a/b/` → `a/b/index.html`
/// (Astro's directory format); otherwise the exact file. Paths containing `..` never resolve.
pub fn asset_for(path: &str) -> Option<&'static Asset> {
    if path.contains("..") {
        return None;
    }
    let p = path.trim_start_matches('/');
    let find = |want: &str| UI_ASSETS.iter().find(|a| a.path == want);
    if p.is_empty() {
        return find("index.html");
    }
    if let Some(a) = find(p) {
        return Some(a);
    }
    let dir = p.trim_end_matches('/');
    let mut idx = [0u8; 256];
    let tail = b"/index.html";
    if dir.len() + tail.len() > idx.len() {
        return None;
    }
    idx[..dir.len()].copy_from_slice(dir.as_bytes());
    idx[dir.len()..dir.len() + tail.len()].copy_from_slice(tail);
    find(core::str::from_utf8(&idx[..dir.len() + tail.len()]).ok()?)
}

/// What to send back.
pub enum Body {
    /// An embedded file (streamed from the image, never copied).
    Static(&'static [u8]),
    /// `len` bytes rendered into the caller's scratch buffer.
    Scratch(usize),
    /// Switch the connection to a long-lived SSE stream.
    Sse,
}

pub struct Response {
    pub status: u16,
    pub ctype: &'static str,
    pub body: Body,
}

fn json(scratch: &mut [u8], f: impl FnOnce(&mut JsonBuf)) -> Response {
    let mut w = JsonBuf::new(scratch);
    f(&mut w);
    let ok = !w.overflow;
    let len = w.len;
    if ok {
        Response { status: 200, ctype: "application/json", body: Body::Scratch(len) }
    } else {
        let mut w = JsonBuf::new(scratch);
        w.raw("{\"error\":\"response too large\"}");
        Response { status: 500, ctype: "application/json", body: Body::Scratch(w.len) }
    }
}

/// Route one request against the device state. `scratch` receives rendered JSON.
pub fn handle(req: &Req, st: &McState, scratch: &mut [u8]) -> Response {
    if !req.get {
        return json(scratch, |w| w.raw("{\"error\":\"method not allowed\"}")).with_status(405);
    }
    let limit = |dflt: u32, max: u32| query_u32(req.query, "limit").unwrap_or(dflt).clamp(1, max) as usize;
    match req.path {
        "/api/detections" => json(scratch, |w| st.render_detections(limit(200, 500), w)),
        "/api/incidents" => json(scratch, |w| st.render_incidents(limit(50, 500), w)),
        "/api/qsecbit" => json(scratch, |w| st.render_qsecbit(limit(20, 1000), w)),
        // No engine registry on heqk yet: an EMPTY list keeps every engine row honestly badged
        // "mock" in the Detect UI rather than inventing live engines.
        "/api/engines" => json(scratch, |w| w.raw("{\"engines\":[]}")),
        "/api/health" => json(scratch, |w| {
            use core::fmt::Write;
            // An unarmed rule plane (0 active rules) passes everything — report it, never hide it.
            let rules = crate::rules::active_rules();
            let _ = write!(w, "{{\"status\":\"{}\",\"substrate\":\"heqk\",\"rules_active\":{},\"seen\":{},\"forwarded\":{},\"dropped\":{},\"detections\":{}}}",
                if rules == 0 { "degraded: rule plane not armed" } else { "ok" }, rules, st.seen, st.forwarded, st.dropped, st.detections());
        }),
        "/api/stream" => Response { status: 200, ctype: "text/event-stream", body: Body::Sse },
        p if p.starts_with("/api/") => json(scratch, |w| w.raw("{\"error\":\"not implemented on heqk\"}")).with_status(404),
        p => match asset_for(p) {
            Some(a) => Response { status: 200, ctype: a.ctype, body: Body::Static(a.body) },
            None => json(scratch, |w| w.raw("{\"error\":\"not found\"}")).with_status(404),
        },
    }
}

impl Response {
    fn with_status(mut self, s: u16) -> Self {
        self.status = s;
        self
    }

    pub fn body_len(&self) -> Option<usize> {
        match self.body {
            Body::Static(b) => Some(b.len()),
            Body::Scratch(n) => Some(n),
            Body::Sse => None,
        }
    }
}

fn reason(status: u16) -> &'static str {
    match status {
        200 => "OK",
        400 => "Bad Request",
        404 => "Not Found",
        405 => "Method Not Allowed",
        _ => "Internal Server Error",
    }
}

/// Write the status line + headers for `resp` into `out`; returns the length.
pub fn write_head(resp: &Response, out: &mut [u8]) -> usize {
    use core::fmt::Write;
    let mut w = JsonBuf::new(out);
    let _ = write!(w, "HTTP/1.1 {} {}\r\nContent-Type: {}\r\nServer: heqk\r\nAccess-Control-Allow-Origin: *\r\n",
        resp.status, reason(resp.status), resp.ctype);
    match resp.body_len() {
        Some(n) => {
            let _ = write!(w, "Content-Length: {}\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n", n);
        }
        None => w.raw("Cache-Control: no-cache\r\nConnection: keep-alive\r\n\r\n"),
    }
    w.len
}

/// A complete `400 Bad Request` (no body).
pub const BAD_REQUEST: &[u8] = b"HTTP/1.1 400 Bad Request\r\nContent-Length: 0\r\nConnection: close\r\n\r\n";

/// Frame one SSE `update` event carrying `st`'s change payload into `out`.
pub fn sse_update(st: &McState, out: &mut [u8]) -> usize {
    let mut w = JsonBuf::new(out);
    w.raw("event: update\ndata: ");
    st.render_update(&mut w);
    w.raw("\n\n");
    if w.overflow { 0 } else { w.len }
}

pub const SSE_PING: &[u8] = b": ping\n\n";

/// `[P-mc]` — the on-device Mission Control server logic, proven without a network: parse, route,
/// JSON shapes the UI parses (detections/incidents/qsecbit/engines/health), SSE framing, static
/// index mapping + `..` refusal, and 405/404/400 handling. Pure; QEMU-provable.
#[cfg(not(feature = "cm5"))]
pub fn mc_selftest() -> bool {
    macro_rules! kprint { ($($t:tt)*) => { arch_aarch64::_print(format_args!($($t)*)) }; }
    let has = |hay: &[u8], needle: &str| hay.windows(needle.len()).any(|w| w == needle.as_bytes());
    let mut st = McState::new();
    st.set_clock(1_700_000_000_000, 0, 1000); // 1 kHz: tick == ms
    st.push_event(&crate::events::Event { ts: 5_000, src: 0x0A00_0202, rule_id: 1, severity: 5, verdict: 2, class: crate::verdict::CLASS_FRAMEDROP });
    st.push_event(&crate::events::Event { ts: 6_000, src: 0x0A00_0202, rule_id: 113, severity: 3, verdict: 2, class: crate::verdict::CLASS_QUARANTINE });
    st.push_event(&crate::events::Event { ts: 7_000, src: 0x1122_3344, rule_id: 122, severity: 3, verdict: 2, class: crate::verdict::CLASS_RATELIMIT_OVER });
    st.sample_qsecbit(1_000, 0);
    st.sample_qsecbit(8_000, 40); // 40 points inside the window → risk 40/60
    let mut scratch = [0u8; 8192];

    let req = |raw: &'static [u8]| parse(raw);
    let get = |p: &'static [u8], st: &McState, sc: &mut [u8]| -> (u16, usize) {
        let r = parse(p).unwrap();
        let resp = handle(&r, st, sc);
        (resp.status, match resp.body { Body::Scratch(n) => n, _ => 0 })
    };

    let (s1, n1) = get(b"GET /api/detections?limit=50 HTTP/1.1\r\nHost: d\r\n\r\n", &st, &mut scratch);
    let d = &scratch[..n1];
    let det_ok = s1 == 200 && has(d, "\"count\":3") && has(d, "\"rule_id\":1200001") && has(d, "Known C2 port 4444 (DROP, framedrop)")
        && has(d, "\"src_ip\":\"10.0.2.2\"") && has(d, "\"severity\":2") && has(d, "\"mitre\":\"T1571\"")
        && has(d, "\"ts\":1700000005.000") && !has(d, "17.34.51.68") /* MAC-hash src never rendered as an IP */;
    let (s2, n2) = get(b"GET /api/incidents HTTP/1.1\r\n\r\n", &st, &mut scratch);
    let i = &scratch[..n2];
    let inc_ok = s2 == 200 && has(i, "\"count\":1") && has(i, "\"device_ip\":\"10.0.2.2\"") && has(i, "\"priority\":\"High\"")
        && has(i, "\"threat_score\":0.8") && has(i, "(2 detections)");
    let (s3, n3) = get(b"GET /api/qsecbit?limit=5 HTTP/1.1\r\n\r\n", &st, &mut scratch);
    let q = &scratch[..n3];
    let qs_ok = s3 == 200 && has(q, "\"latest\":{\"ts\":1700000008.000,\"score\":0.666,\"band\":\"AMBER\"}") && has(q, "\"count\":2");
    let (s4, n4) = get(b"GET /api/engines HTTP/1.1\r\n\r\n", &st, &mut scratch);
    let eng_ok = s4 == 200 && &scratch[..n4] == b"{\"engines\":[]}";
    let (s5, _) = get(b"GET /api/nope HTTP/1.1\r\n\r\n", &st, &mut scratch);
    let (s6, _) = get(b"POST /api/detections HTTP/1.1\r\n\r\n", &st, &mut scratch);
    let errs_ok = s5 == 404 && s6 == 405
        && req(b"GET /api/x HTTP/1.1\r\n") == Err(ParseErr::Incomplete)
        && req(b"garbage\r\n\r\n") == Err(ParseErr::Bad)
        && asset_for("/../../etc/passwd").is_none();
    let sse_ok = matches!(handle(&parse(b"GET /api/stream HTTP/1.1\r\n\r\n").unwrap(), &st, &mut scratch).body, Body::Sse) && {
        let n = sse_update(&st, &mut scratch);
        n > 0 && scratch[..n].starts_with(b"event: update\ndata: {\"detections\":[") && scratch[..n].ends_with(b"]}\n\n")
    };
    // Overflow honesty: a small buffer sheds rows from the END but stays a VALID document (200,
    // fewer rows, an honest count); a buffer too small for even the empty document is a valid
    // 500 JSON error — never a truncated document.
    let mut small = [0u8; 400];
    let shed = handle(&parse(b"GET /api/detections HTTP/1.1\r\n\r\n").unwrap(), &st, &mut small);
    let shed_ok = shed.status == 200 && matches!(shed.body, Body::Scratch(n) if small[..n].ends_with(b"}") && !has(&small[..n], "\"count\":3"));
    let mut tiny = [0u8; 8];
    let big = handle(&parse(b"GET /api/detections HTTP/1.1\r\n\r\n").unwrap(), &st, &mut tiny);
    let ovf_ok = shed_ok && big.status == 500;
    let pass = det_ok && inc_ok && qs_ok && eng_ok && errs_ok && sse_ok && ovf_ok;
    kprint!(" [P-mc] {} — on-device Mission Control server (ADR 0047): detections(rule band+catalogue+class+epoch ts, MAC-hash never an IP)={} incidents(per-source, worst-sev priority)={} qsecbit(windowed risk+band)={} engines(honest empty)={} 404/405/400/..-refused={} SSE update framing={} overflow→valid-500={} (ui assets embedded: {})\n",
        if pass { "PASS" } else { "FAIL" }, det_ok, inc_ok, qs_ok, eng_ok, errs_ok, sse_ok, ovf_ok, UI_ASSETS.len());
    pass
}
