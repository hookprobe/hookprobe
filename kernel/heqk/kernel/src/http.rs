    let unclaimed_ok = handle(&parse(b"GET /api/detections HTTP/1.1\r\n\r\n").unwrap(), &st, &mut unclaimed, 0, || Some([0; 16]), &mut scratch).status == 403
        && handle(&parse(b"POST /api/login HTTP/1.1\r\nContent-Length: 11\r\n\r\ntoken=guess").unwrap(), &st, &mut unclaimed, 0, || Some([0; 16]), &mut scratch).status == 403;
    let auth_ok = unauth_api && unauth_page && public_health && bad_login && login_ok && cookie_hdr_ok && unclaimed_ok;

    // Authenticated requests from here on (the browser's cookie).
    let mut authed: [u8; 512] = [0; 512];
    let get = |p: &'static [u8], st: &McState, auth: &mut Auth, sc: &mut [u8], buf: &mut [u8; 512]| -> (u16, usize) {
        // splice "Cookie: hq_session=<id>" into the request before the blank line
        let end = p.len() - 4;
        let ck = b"\r\nCookie: hq_session=5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a";
        buf[..end].copy_from_slice(&p[..end]);
        buf[end..end + ck.len()].copy_from_slice(ck);
        buf[end + ck.len()..end + ck.len() + 4].copy_from_slice(b"\r\n\r\n");
        let len = end + ck.len() + 4;
        let r = parse(&buf[..len]).unwrap();
        let resp = handle(&r, st, auth, 1, || Some([0; 16]), sc);
        (resp.status, match resp.body { Body::Scratch(n) => n, _ => 0 })
    };
    let (s1, n1) = get(b"GET /api/detections?limit=50 HTTP/1.1\r\nHost: d\r\n\r\n", &st, &mut auth, &mut scratch, &mut authed);
    let d = &scratch[..n1];
    let det_ok = s1 == 200 && has(d, "\"count\":3") && has(d, "\"rule_id\":1200001") && has(d, "Known C2 port 4444 (DROP, framedrop)")
        && has(d, "\"src_ip\":\"10.0.2.2\"") && has(d, "\"severity\":2") && has(d, "\"mitre\":\"T1571\"")
        && has(d, "\"ts\":1700000005.000") && has(d, "\"dst_ip\":\"10.0.2.15\",\"dst_port\":4444") && !has(d, "17.34.51.68") /* MAC-hash src never rendered as an IP */;
    let (s2, n2) = get(b"GET /api/incidents HTTP/1.1\r\n\r\n", &st, &mut auth, &mut scratch, &mut authed);
    let i = &scratch[..n2];
    let inc_ok = s2 == 200 && has(i, "\"count\":1") && has(i, "\"device_ip\":\"10.0.2.2\"") && has(i, "\"priority\":\"High\"")
        && has(i, "\"threat_score\":0.8") && has(i, "(2 detections)");
    let (s3, n3) = get(b"GET /api/qsecbit?limit=5 HTTP/1.1\r\n\r\n", &st, &mut auth, &mut scratch, &mut authed);
    let q = &scratch[..n3];
    let qs_ok = s3 == 200 && has(q, "\"latest\":{\"ts\":1700000008.000,\"score\":0.666,\"band\":\"AMBER\"}") && has(q, "\"count\":2");
    let (s4, n4) = get(b"GET /api/engines HTTP/1.1\r\n\r\n", &st, &mut auth, &mut scratch, &mut authed);
    let eng_ok = s4 == 200 && &scratch[..n4] == b"{\"engines\":[]}";
    let (s5, _) = get(b"GET /api/nope HTTP/1.1\r\n\r\n", &st, &mut auth, &mut scratch, &mut authed);
    let (s6, _) = get(b"POST /api/detections HTTP/1.1\r\n\r\n", &st, &mut auth, &mut scratch, &mut authed);
    let errs_ok = s5 == 404 && s6 == 405
        && req(b"GET /api/x HTTP/1.1\r\n") == Err(ParseErr::Incomplete)
        && req(b"garbage\r\n\r\n") == Err(ParseErr::Bad)
        && asset_for("/../../etc/passwd").is_none();
    let sse_ok = matches!(handle(&parse(b"GET /api/stream HTTP/1.1\r\nCookie: hq_session=5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a\r\n\r\n").unwrap(), &st, &mut auth, 1, || Some([0; 16]), &mut scratch).body, Body::Sse)
        && !matches!(handle(&parse(b"GET /api/stream HTTP/1.1\r\n\r\n").unwrap(), &st, &mut auth, 1, || Some([0; 16]), &mut scratch).body, Body::Sse) && {
        let n = sse_update(&st, &mut scratch);
        n > 0 && scratch[..n].starts_with(b"event: update\ndata: {\"detections\":[") && scratch[..n].ends_with(b"]}\n\n")
    };
    // Overflow honesty: a small buffer sheds rows from the END but stays a VALID document (200,
    // fewer rows, an honest count); a buffer too small for even the empty document is a valid
    // 500 JSON error — never a truncated document.
    let mut small = [0u8; 400];
    let shed = handle(&parse(b"GET /api/detections HTTP/1.1\r\nCookie: hq_session=5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a\r\n\r\n").unwrap(), &st, &mut auth, 1, || Some([0; 16]), &mut small);
    let shed_ok = shed.status == 200 && matches!(shed.body, Body::Scratch(n) if small[..n].ends_with(b"}") && !has(&small[..n], "\"count\":3"));
    let mut tiny = [0u8; 8];
    let big = handle(&parse(b"GET /api/detections HTTP/1.1\r\nCookie: hq_session=5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a\r\n\r\n").unwrap(), &st, &mut auth, 1, || Some([0; 16]), &mut tiny);
    let ovf_ok = shed_ok && big.status == 500;
    // N4 — wall clock: a strict SNTP reply sets it and moves pre-sync rows; forged replies refused.
    let time_ok = {
        let nonce = 0x1122_3344_5566_7788u64;
        let mut r = [0u8; 48];
        r[0] = 0x24; // LI 0 | VN 4 | Mode 4 (server)
        r[1] = 2;
        r[24..32].copy_from_slice(&nonce.to_be_bytes());
        let ntp_secs = 1_800_000_000u64 + 2_208_988_800;
        r[40..44].copy_from_slice(&(ntp_secs as u32).to_be_bytes());
        r[44..48].copy_from_slice(&0x8000_0000u32.to_be_bytes()); // .5 s
        let good = crate::mcstate::sntp_parse_strict(&r, nonce) == Some(1_800_000_000_500);
        let wrong_nonce = crate::mcstate::sntp_parse_strict(&r, nonce ^ 1).is_none();
        let mut kod = r;
        kod[1] = 0; // kiss-o'-death
        let mut client = r;
        client[0] = 0x23;
        let mut old = r;
        old[40..44].copy_from_slice(&((1_600_000_000u64 + 2_208_988_800) as u32).to_be_bytes());
        let refused = crate::mcstate::sntp_parse_strict(&kod, nonce).is_none()
            && crate::mcstate::sntp_parse_strict(&client, nonce).is_none()
            && crate::mcstate::sntp_parse_strict(&old, nonce).is_none()
            && crate::mcstate::sntp_parse_strict(&r[..47], nonce).is_none();
        // An unsynced state at epoch 0: a detection at tick 5_000 reads 5_000 ms; syncing to
        // 1.8e12 at tick 10_000 moves it to 1.8e12 - 5_000. A later 2-h step is refused.
        let mut t = McState::new();
        t.set_clock(0, 0, 1000);
        t.push_event(&crate::events::Event { ts: 5_000, src: 1, rule_id: 1, severity: 5, verdict: 2, class: crate::verdict::CLASS_FRAMEDROP, dst: 0, dport: 0 });
        let before = t.health_ts(0);
        let step = t.sync_clock(1_800_000_000_000, 10_000);
        let after = t.health_ts(0);
        let synced = step == Some(1_800_000_000_000 - 10_000) && before == Some(5_000) && after == Some(1_799_999_995_000) && t.clock_synced;
        let small = t.sync_clock(1_800_000_000_000 + 20_000 + 1_000, 30_000) == Some(1_000);
        let big = t.sync_clock(1_800_000_000_000 + 7_200_000 + 40_000, 40_000).is_none();
        // A restored (prior-boot, wall-clock) row is never moved by this boot's clock step.
        let mut r2 = McState::new();
        r2.push_restored(&crate::events::Event { ts: 0, src: 1, rule_id: 1, severity: 5, verdict: 2, class: 0, dst: 0, dport: 0 }, 1_799_000_000_000);
        let _ = r2.sync_clock(1_800_000_000_000, 10_000);
        let pinned = r2.health_ts(0) == Some(1_799_000_000_000);
        // My Network: distinct LAN hosts active in the window; a host silent > 10 min ages out.
        let mut h = McState::new();
        for ip in [0x0A00_0001u32, 0x0A00_0002, 0x0A00_0001] {
            h.note_host(ip, 1_000_000);
        }
        let two = h.hosts_active(1_000_000) == 2; // a repeat sighting is one host
        h.note_host(0x0A00_0003, 1_000_000 + 700_000);
        let hosts_ok = two && h.hosts_active(1_000_000 + 700_000) == 1; // the two silent > 10 min aged out
        good && wrong_nonce && refused && synced && small && big && pinned && hosts_ok
    };
    // ADR 0051 D4: :80 -> https redirect keeps path+query, drops the port; a hostile Host never reaches
    // the Location header; the session cookie gains Secure only over TLS.
    let tls_ok = {
        let mut o = [0u8; 512];
        let r1 = parse(b"GET /detect/feed?x=1 HTTP/1.1\r\nHost: heqk.local:8080\r\n\r\n").unwrap();
        let n1 = https_redirect(&r1, &mut o);
        let red = has(&o[..n1], "HTTP/1.1 308") && has(&o[..n1], "Location: https://heqk.local/detect/feed?x=1\r\n");
        let r6 = parse(b"GET / HTTP/1.1\r\nHost: [fd00::1]:80\r\n\r\n").unwrap();
        let n6 = https_redirect(&r6, &mut o);
        let v6 = has(&o[..n6], "Location: https://[fd00::1]/\r\n");
        let bad = parse(b"GET / HTTP/1.1\r\nHost: evil.com\rSet-Cookie: x=1\r\n\r\n").map_or(true, |r| r.host.is_empty())
            && parse(b"GET / HTTP/1.1\r\nHost: a b/c\r\n\r\n").map_or(true, |r| r.host.is_empty());
        let login = handle(&parse(b"POST /api/login HTTP/1.1\r\nContent-Length: 29\r\n\r\ntoken=hq-owner-selftest-token").unwrap(), &st, &mut auth, 0, || Some([0x5A; 16]), &mut scratch);
        let mut hh = [0u8; 512];
        let a = write_head_tls(&login, &mut hh, true);
        let sec = has(&hh[..a], "Max-Age=43200; Secure\r\n");
        let b = write_head_tls(&login, &mut hh, false);
        let plain = !has(&hh[..b], "Secure");
        // keep-alive (HTTP/1.1 default, Connection: close / HTTP/1.0 end it; `consumed` spans head + body so a
        // pipelined next request survives; the header advertises the limits only when kept)
        let two = b"POST /api/login HTTP/1.1\r\nContent-Length: 5\r\n\r\nabcdeGET / HTTP/1.1\r\n\r\n";
        let ka = parse(two).map_or(false, |r| r.keep_alive && r.consumed == two.len() - 18 && r.body == b"abcde")
            && parse(b"GET / HTTP/1.1\r\nConnection: Close\r\n\r\n").map_or(false, |r| !r.keep_alive)
            && parse(b"GET / HTTP/1.0\r\n\r\n").map_or(false, |r| !r.keep_alive)
            && parse(b"GET / HTTP/1.1\r\nConnection: keep-alive, Upgrade\r\n\r\n").map_or(false, |r| r.keep_alive);
        let h1 = handle(&parse(b"GET /api/health HTTP/1.1\r\n\r\n").unwrap(), &st, &mut auth, 0, || Some([0; 16]), &mut scratch);
        let k = write_head_ka(&h1, &mut hh, false, true);
        let kept = has(&hh[..k], "Connection: keep-alive\r\nKeep-Alive: timeout=15, max=100\r\n");
        let c = write_head_ka(&h1, &mut hh, false, false);
        let closed = has(&hh[..c], "Connection: close\r\n") && !has(&hh[..c], "Keep-Alive");
        // AP image: the WAN facts reach /api/health for the Get Online / Shield tiles.
        let mut sw = McState::new();
        sw.wan = Some(crate::mcstate::WanFacts { up: true, ip: [100, 71, 11, 24], mode: 2, ipv6: true, clients: 3, pkts_out: 10, pkts_in: 20, dns_inspected: 7 });
        let hw = handle(&parse(b"GET /api/health HTTP/1.1\r\nCookie: hq_session=5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a\r\n\r\n").unwrap(), &sw, &mut auth, 1, || Some([0; 16]), &mut scratch);
        let wan_ok = matches!(hw.body, Body::Scratch(n) if has(&scratch[..n], "\"wan\":{\"up\":true,\"ip\":\"100.71.11.24\",\"mode\":\"pppoe\",\"ipv6\":true,\"clients\":3,\"pkts_out\":10,\"pkts_in\":20,\"dns_inspected\":7}}"));
        red && v6 && bad && sec && plain && ka && kept && closed && wan_ok
    };
    let pass = auth_ok && det_ok && inc_ok && qs_ok && eng_ok && errs_ok && sse_ok && ovf_ok && time_ok && tls_ok;
    kprint!(" [P-mc] {} — on-device Mission Control server (ADR 0047): owner-auth(401/302/public-health/bad-login/login→HttpOnly cookie/no-CORS/unclaimed-refuses)={} detections(rule band+catalogue+class+epoch ts, MAC-hash never an IP)={} incidents(per-source, worst-sev priority)={} qsecbit(windowed risk+band)={} engines(honest empty)={} 404/405/400/..-refused={} SSE update framing={} overflow→valid-500={} sntp(strict nonce/mode/stratum/floor + rows moved + >1h re-step refused)={} https(308 keeps path/query, drops port, hostile Host refused, Secure only over TLS) + keep-alive(1.1 default, close/1.0 end it, pipelined bytes kept, limits advertised)={} (ui assets embedded: {})\n",
        if pass { "PASS" } else { "FAIL" }, auth_ok, det_ok, inc_ok, qs_ok, eng_ok, errs_ok, sse_ok, ovf_ok, time_ok, tls_ok, UI_ASSETS.len());
