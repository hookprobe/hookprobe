/// M5.3 — VERIFY a module's Ed25519 signature (kernel = trust root); on success return the
/// EXACT module bytes to hand to the EL0 wasmi host, else `None` (fail-closed: a
/// tampered/unsigned module is refused BEFORE it can cross into EL0). Unlike
/// `verified_classify_expr` (which also decodes classify() for the bespoke stub), wasmi
/// consumes the whole module, so this returns the whole verified image.
#[cfg(all(not(feature = "cm5"), feature = "wasmhost"))]
pub fn verified_module<'a>(wasm: &'a [u8], pk: &[u8], sig: &[u8]) -> Option<&'a [u8]> {
    if verify_module(wasm, pk, sig) {
        Some(wasm)
    } else {
        None
    }
}

/// M5.2b — the in-kernel REFERENCE of the exact 5-opcode execution the EL0 host performs,
/// so the [P-wasm-el0] proof can assert EL0-verdict == reference-verdict (the EL0 engine
/// is the SAME logic, only relocated across the EL1/EL0 boundary). Reuses `exec_expr`.
#[cfg(not(feature = "cm5"))]
pub fn reference_exec(expr: &[u8], port: i32) -> Option<i32> {
    exec_expr(expr, &[port])
}

// ================================ the proof ==================================

/// The result of the beachhead self-test, surfaced to the [P-wasm] gate print.
pub struct WasmProof {
    /// (a) signed module verified -> ran -> both vectors correct.
    pub a_verify_run: bool,
    /// (b) a TAMPERED module was REJECTED and NEVER interpreted (fail-closed).
    pub b_fail_closed: bool,
    /// (b') an UNSIGNED module (bad signature) was likewise refused.
    pub b_unsigned: bool,
    /// classify(4444) observed under (a) — expected 1.
    pub bad_result: i32,
    /// classify(443) observed under (a) — expected 0.
    pub ok_result: i32,
}

/// Run the M5.2 beachhead proof. Deterministic, no scheduler needed (like the cap /
/// ELF-parser self-tests): the interpreter runs synchronously in-kernel.
pub fn wasmhost_selftest() -> WasmProof {
    // ---- (a) SIGNED -> VERIFIED -> RUN -> correct against a known vector ----
    let bad = run_verified(FIXTURE_WASM, FIXTURE_PK, FIXTURE_SIG, BAD_PORT);
    let ok = run_verified(FIXTURE_WASM, FIXTURE_PK, FIXTURE_SIG, 443);
    let bad_result = bad.unwrap_or(-1);
    let ok_result = ok.unwrap_or(-1);
    let a_verify_run = bad == Some(1) && ok == Some(0);

    // ---- (b) TAMPERED -> REJECTED, and PROVABLY never interpreted ----
    // Flip one code byte (i32.eq 0x46 -> i32.ne 0x47): the SIGNATURE is the ONLY thing
    // standing between a tampered detector and execution. Arm the tripwire fresh, then
    // assert it stays clear.
    INTERPRETED.store(false, Ordering::SeqCst);
    let mut tampered = [0u8; 46];
    let n = FIXTURE_WASM.len();
    tampered[..n].copy_from_slice(FIXTURE_WASM);
    // The `i32.eq` opcode is the 3rd-from-last byte (…0x46, 0x0b end); flip to `i32.ne`.
    tampered[n - 3] ^= 0x01;
    let t = run_verified(&tampered[..n], FIXTURE_PK, FIXTURE_SIG, BAD_PORT);
    let b_fail_closed = t.is_none() && !INTERPRETED.load(Ordering::SeqCst);

    // ---- (b') UNSIGNED / wrong-signature -> refused the same way ----
    let mut badsig = [0u8; 64];
    badsig.copy_from_slice(FIXTURE_SIG);
    badsig[0] ^= 0xff;
    let u = run_verified(FIXTURE_WASM, FIXTURE_PK, &badsig, BAD_PORT);
    let b_unsigned = u.is_none();

    WasmProof {
        a_verify_run,
        b_fail_closed,
        b_unsigned,
        bad_result,
        ok_result,
    }
}
