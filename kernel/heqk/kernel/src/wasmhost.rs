//! M5.2 (Track C) — the Wasm-host BEACHHEAD: verify-then-run ONE signed `.wasm`
//! module on heqk. This is the FIRST minimal sliver of the multi-year Wasm-host road
//! (ADR 0044 D4 #2 / D5, `docs/design/heqk-module-runtime.md` §M5.2). It proves the
//! CONCEPT end-to-end — "a signed wasm module is VERIFIED, then its exported fn is
//! executed on heqk, fail-closed" — and NOTHING more.
//!
//! ENGINE CHOICE (the load-bearing feasibility answer, reported honestly):
//!   * `wasmi` (pure-Rust no_std interpreter) DOES build for
//!     aarch64-unknown-none-softfloat under build-std with `alloc` only — ZERO std
//!     leakage, no getrandom — and runs a memoryless module in ~7 KiB of heap (proven
//!     in a host harness AND it compiled into this kernel). The feasibility question is
//!     answered YES.
//!   * BUT folding wasmi into the kernel balloons `.text` by ~2 MiB (~15 transitive
//!     crates) AND the enlarged image faulted at MMU-enable, because the QEMU MMU's
//!     `build_wx_ram` W^X-maps only the SINGLE 2 MiB block holding `text_start` — a
//!     latent limit wasmi merely exposed. That is a disproportionate TCB expansion +
//!     collateral MMU rework for a ONE-MODULE proof.
//!   * So this sliver ships a BESPOKE MINIMAL interpreter (below): zero dependencies,
//!     ~1 KiB of code, stays inside one 2 MiB block, no MMU change, deterministic. The
//!     design doc sanctions exactly this ("bespoke minimal interpreter — viable for a
//!     one-module beachhead"). wasmi stays the documented path for the eventual FULL
//!     host, gated on the MMU multi-block-W^X fix + an explicit TCB-expansion decision.
//!
//! WHAT THIS IS NOT (brutally scoped, ADR 0044 D5): not a conformant Wasm engine — it
//! decodes the MVP subset (type/function/export/code sections + local.get / i32.const /
//! i32.add / i32.eq / end) that runs the ONE fixture; not the production WASI host, not
//! WASI 0.2/0.3 components, not a `wasm32-wasip1` shim, not the signed catalogue
//! (napse-dpi/aegis-guard/qsecbit/dnsxai), not EL0-hosted-at-detection-parity, not
//! metal. Those are the genuine multi-year road + Gate R.
//!
//! SIGNATURE PRIMITIVE (honest): heqk's REAL per-artifact hybrid is Ed25519 +
//! SLH-DSA-SHA2-128s (`boot-abi::verify`, image-level) — NOT ML-DSA-65 (which is NOT on
//! heqk; only roadmap-named in securechannel.rs). This beachhead verifies with the
//! Ed25519 leg — the kernel's ALWAYS-ON primitive (`ed25519-compact`, the same crate
//! `attest_svc` signs with) — so the base TCB is untouched. The SLH-DSA PQ co-leg
//! (already the boot verifier) is deliberately kept out of the default kernel and added
//! at catalogue-parity time (M5.3), not for a one-module sliver.

#![allow(dead_code)]

