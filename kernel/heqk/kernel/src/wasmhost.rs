const FIXTURE_WASM: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/fixture_classify.wasm"));
const FIXTURE_PK: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/fixture_classify.pk"));
const FIXTURE_SIG: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/fixture_classify.sig"));

/// M5.3 (c) — a SIGNED, memoryless module whose `classify` body is `unreachable` (it TRAPS
/// on call). Same type/export as the good fixture, so the EL0 wasmi host loads it
/// identically; the trap only fires at call time and is contained by wasmi AT EL0.
#[cfg(all(not(feature = "cm5"), feature = "wasmhost"))]
const FIXTURE_TRAP_WASM: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/fixture_trap.wasm"));
#[cfg(all(not(feature = "cm5"), feature = "wasmhost"))]
const FIXTURE_TRAP_PK: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/fixture_trap.pk"));
#[cfg(all(not(feature = "cm5"), feature = "wasmhost"))]
const FIXTURE_TRAP_SIG: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/fixture_trap.sig"));

/// The known-bad backdoor port the fixture predicate matches (rules.rs rule 1
/// "block-port-4444"). `classify(BAD_PORT) == 1`, everything else `== 0`.
const BAD_PORT: i32 = 4444;

/// Tripwire: set true the instant the interpreter is entered. The (b) sub-proof asserts
/// it stays FALSE for a tampered module — proving the tampered bytes are never
/// interpreted, only refused at the signature gate.
static INTERPRETED: AtomicBool = AtomicBool::new(false);

// ============================ signature gate =================================

/// FAIL-CLOSED signature gate. Verify the Ed25519 signature over the EXACT module bytes
/// against the embedded module-signing public key. Any malformed key/sig, or any
/// tamper, yields `false` — the module is refused. (Ed25519 signs arbitrary-length
/// messages directly; signing the artifact bytes is ADR-0016-shaped artifact signing.)
fn verify_module(wasm: &[u8], pk_bytes: &[u8], sig_bytes: &[u8]) -> bool {
    use ed25519_compact::{PublicKey, Signature};
    (|| {
        let pk = PublicKey::from_slice(pk_bytes).ok()?;
        let sig = Signature::from_slice(sig_bytes).ok()?;
        pk.verify(wasm, &sig).ok()
    })()
    .is_some()
}

// ===================== bespoke minimal Wasm interpreter ======================
// Bounds-safe by construction: every read is a `get(..)`; a malformed module can only
// ever return `None`, never panic or read OOB. This is a beachhead decoder, not a
// validator — the SIGNATURE is the trust boundary; this just executes a trusted module.

const WASM_MAGIC: [u8; 4] = [0x00, 0x61, 0x73, 0x6d];
const SEC_EXPORT: u8 = 7;
const SEC_CODE: u8 = 10;

/// Unsigned LEB128 (u32). Advances `pos`. `None` on truncation/overlong.
fn leb_u32(b: &[u8], pos: &mut usize) -> Option<u32> {
    let mut result: u32 = 0;
    let mut shift = 0u32;
    loop {
        let byte = *b.get(*pos)?;
        *pos += 1;
        result |= ((byte & 0x7f) as u32).checked_shl(shift)?;
        if byte & 0x80 == 0 {
            return Some(result);
        }
        shift += 7;
        if shift >= 32 {
            return None;
        }
    }
}

/// Signed LEB128 (i32) — the encoding `i32.const` uses. Advances `pos`.
fn leb_i32(b: &[u8], pos: &mut usize) -> Option<i32> {
    let mut result: i32 = 0;
    let mut shift = 0u32;
    loop {
        let byte = *b.get(*pos)?;
        *pos += 1;
        result |= ((byte & 0x7f) as i32).checked_shl(shift)?;
        shift += 7;
        if byte & 0x80 == 0 {
            // sign-extend if the sign bit of the last group is set
            if shift < 32 && (byte & 0x40) != 0 {
                result |= (-1i32) << shift;
            }
            return Some(result);
        }
        if shift >= 32 {
            return None;
        }
    }
}

/// Iterate the section list, returning the payload slice of the first section with id
/// `want`. `None` if absent/malformed. Skips every other section by its declared length.
fn find_section(wasm: &[u8], want: u8) -> Option<&[u8]> {
    if wasm.get(0..4)? != WASM_MAGIC {
        return None;
    }
    // bytes 4..8 = version (little-endian u32, must be 1)
    if wasm.get(4..8)? != [0x01, 0x00, 0x00, 0x00] {
        return None;
    }
    let mut pos = 8usize;
    while pos < wasm.len() {
        let id = *wasm.get(pos)?;
        pos += 1;
        let len = leb_u32(wasm, &mut pos)? as usize;
        let start = pos;
        let end = start.checked_add(len)?;
        if end > wasm.len() {
            return None;
        }
        if id == want {
            return wasm.get(start..end);
        }
        pos = end;
    }
    None
}

/// Resolve an exported function name -> function index (export kind 0x00 = func).
fn export_func_index(wasm: &[u8], name: &[u8]) -> Option<u32> {
    let sec = find_section(wasm, SEC_EXPORT)?;
    let mut pos = 0usize;
    let count = leb_u32(sec, &mut pos)?;
    for _ in 0..count {
        let nlen = leb_u32(sec, &mut pos)? as usize;
        let nend = pos.checked_add(nlen)?;
        let ename = sec.get(pos..nend)?;
        pos = nend;
        let kind = *sec.get(pos)?;
        pos += 1;
        let idx = leb_u32(sec, &mut pos)?;
        if kind == 0x00 && ename == name {
            return Some(idx);
        }
    }
    None
}

/// Return the code-body expression bytes (after the local-declaration vector) for
/// function index `func_idx`. No imported functions in this beachhead, so the code
/// section is indexed directly by `func_idx`.
fn func_expr(wasm: &[u8], func_idx: u32) -> Option<&[u8]> {
    let sec = find_section(wasm, SEC_CODE)?;
    let mut pos = 0usize;
    let count = leb_u32(sec, &mut pos)?;
    for i in 0..count {
        let body_size = leb_u32(sec, &mut pos)? as usize;
        let body_start = pos;
        let body_end = body_start.checked_add(body_size)?;
        let body = sec.get(body_start..body_end)?;
        if i == func_idx {
            // Skip the local-declaration vector: count then count*(n:u32, valtype:1).
            let mut bp = 0usize;
            let ldecls = leb_u32(body, &mut bp)?;
            for _ in 0..ldecls {
                let _n = leb_u32(body, &mut bp)?;
                let _vt = *body.get(bp)?;
                bp += 1;
            }
            return body.get(bp..);
        }
        pos = body_end;
    }
    None
}

/// Execute an expression over a tiny operand stack, with `locals` seeded from the call
/// args. Supports the MVP opcode subset the fixture uses. Fail-closed: an unknown
/// opcode, a stack under/overflow, or a truncated immediate returns `None` — a
/// malformed module can neither escape nor produce a bogus verdict.
fn exec_expr(expr: &[u8], locals: &[i32]) -> Option<i32> {
    const STACK_MAX: usize = 32;
    let mut stack = [0i32; STACK_MAX];
    let mut sp = 0usize;
    let mut pos = 0usize;
    macro_rules! push {
        ($v:expr) => {{
            if sp >= STACK_MAX {
                return None;
            }
            stack[sp] = $v;
            sp += 1;
        }};
    }
    macro_rules! pop {
        () => {{
            if sp == 0 {
                return None;
            }
            sp -= 1;
            stack[sp]
        }};
    }
    while pos < expr.len() {
        let op = expr[pos];
        pos += 1;
        match op {
            0x20 => {
                // local.get idx
                let idx = leb_u32(expr, &mut pos)? as usize;
                push!(*locals.get(idx)?);
            }
            0x41 => {
                // i32.const value
                let v = leb_i32(expr, &mut pos)?;
                push!(v);
            }
            0x6a => {
                // i32.add
                let b = pop!();
                let a = pop!();
                push!(a.wrapping_add(b));
            }
            0x46 => {
                // i32.eq
                let b = pop!();
                let a = pop!();
                push!((a == b) as i32);
            }
            0x0b => {
                // end -> the single result is the top of the stack
                if sp == 0 {
                    return None;
                }
                return Some(stack[sp - 1]);
            }
            _ => return None, // unknown opcode -> refuse (fail-closed)
        }
    }
    None // ran off the end without `end`
}

/// Interpret the (already-verified) module and evaluate its exported `classify(port)`.
/// Sets the INTERPRETED tripwire so the (b) sub-proof can prove the tampered path never
/// reaches here.
fn interpret_classify(wasm: &[u8], port: i32) -> Option<i32> {
    INTERPRETED.store(true, Ordering::SeqCst);
    let idx = export_func_index(wasm, b"classify")?;
    let expr = func_expr(wasm, idx)?;
    exec_expr(expr, &[port])
}

/// The load-bearing composition: VERIFY, then (only if the signature holds) INTERPRET.
/// A failed verification returns `None` WITHOUT ever calling `interpret_classify` — the
/// fail-closed guarantee this whole milestone exists to prove.
fn run_verified(wasm: &[u8], pk: &[u8], sig: &[u8], port: i32) -> Option<i32> {
    if !verify_module(wasm, pk, sig) {
        return None; // refused BEFORE interpretation — never handed to the interpreter
    }
    interpret_classify(wasm, port)
}

// =============================== M5.2b hooks =================================
// The EL0-hosted step (ADR 0044 D4 #2): the SAME signed module, but its 5-opcode
// interpreter runs in an ISOLATED EL0 task and its verdict returns to the kernel over
// the enforced Endpoint-cap IPC. The trust root stays the KERNEL's signing key: the
// kernel verifies (here) and locates the classify() expression (bounds-safe decode, no
// fault possible) BEFORE handing the EL0 host anything — so a tampered/unsigned module
// yields no expression and the EL0 host is never even spawned for it. What moves to EL0
// is the EXECUTION ENGINE (`exec_expr`); the DECODE (find_section/export/func_expr) is
// not execution and stays at EL1. `arch-aarch64/src/syscall.s:wasmhost_stub` is the
// hand-written EL0 form of `exec_expr` (byte-identical opcode semantics).

/// M5.2b — the embedded fixture bytes/keys, for the kernel's EL0-host spawn.
#[cfg(not(feature = "cm5"))]
pub fn fixture() -> (&'static [u8], &'static [u8], &'static [u8]) {
    (FIXTURE_WASM, FIXTURE_PK, FIXTURE_SIG)
}

/// M5.2b — VERIFY the module's Ed25519 signature (kernel = trust root) then, ONLY if it
/// holds, return the exported `classify` code-EXPRESSION bytes (the input the EL0
/// 5-opcode interpreter executes). `None` = fail-closed: a tampered/unsigned module (bad
/// signature) yields NO expression, so the EL0 host is never handed anything to run; a
/// malformed-but-signed module that fails to decode also yields `None`.
#[cfg(not(feature = "cm5"))]
pub fn verified_classify_expr<'a>(wasm: &'a [u8], pk: &[u8], sig: &[u8]) -> Option<&'a [u8]> {
    if !verify_module(wasm, pk, sig) {
        return None; // refused BEFORE decode/hand-off — never crosses into EL0
    }
    let idx = export_func_index(wasm, b"classify")?;
    func_expr(wasm, idx)
}

