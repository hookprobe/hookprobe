    /// WITHIN the grace window, an unclassified device keeps full LAN+WAN reach (observe-not-strand).
    #[test]
    fn onboarding_grace_within_window_keeps_full_access() {
        // Joined 1h ago; 24h grace → still onboarding.
        let now = 1_000_000.0;
        let decls = vec![decl_first_seen("new-phone", Some(now - 3_600.0))];
        let p = resolve_at(&decls, "10.66.0.0/24", "end0", now, DEFAULT_ONBOARDING_GRACE_SECS);
        let d = &p.devices[0];
        assert_eq!(d.policy, NacPolicy::OnboardingGrace, "within grace = full LAN+WAN");
        assert!(!d.reason.contains("EXPIRED"), "must not be expired yet: {}", d.reason);
    }

    /// PAST the grace window, a still-unclassified device reverts to the stricter InternetOnly
    /// default — full access is a bounded welcome, not a permanent free pass — and the reversion
    /// is recorded in `reason` (observable).
    #[test]
    fn onboarding_grace_past_window_reverts_to_internet_only() {
        // Joined 25h ago; 24h grace → expired.
        let now = 1_000_000.0;
        let decls = vec![decl_first_seen("stale-phone", Some(now - 25.0 * 3_600.0))];
        let p = resolve_at(&decls, "10.66.0.0/24", "end0", now, DEFAULT_ONBOARDING_GRACE_SECS);
        let d = &p.devices[0];
        assert_eq!(d.policy, NacPolicy::InternetOnly, "past grace + still unclassified = revert to stricter default");
        assert!(d.reason.contains("EXPIRED") && d.reason.contains("internet_only"), "reversion must be observable: {}", d.reason);
    }

