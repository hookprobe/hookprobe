    /// D17 legit-passes proof at the render layer: an onboarding-grace device's MAC is bound into
    /// `onboarding_macs` (never `internet_only_macs`/`blocked_macs`) and NO drop rule in the
    /// generated nft ever targets that set — it reaches the local printer/NAS/Chromecast (LAN) and
    /// the internet (WAN) exactly like a full_access device, just observed via a log line.
    #[test]
    fn onboarding_grace_device_reaches_lan_and_wan_and_is_only_logged_not_dropped() {
        let mut cam = dev("new-phone", "aa:bb:cc:00:11:22", NacPolicy::OnboardingGrace);
        cam.reason = "onboarding grace (unclassified, new device)".into();
        let f = render_nft(&plan(vec![cam]));
        assert!(f.content.contains("add element inet hookprobe_nac onboarding_macs { aa:bb:cc:00:11:22 }"), "bound into onboarding_macs");
        assert!(
            f.content.contains("ether saddr @onboarding_macs log prefix"),
            "onboarding traffic must be logged for observability"
        );
        // No rule anywhere drops @onboarding_macs — full LAN+WAN reach, only observed.
        assert!(!f.content.contains("@onboarding_macs oifname"), "must never drop onboarding traffic to the WAN");
        assert!(!f.content.contains("@onboarding_macs ip daddr"), "must never drop onboarding traffic to the LAN");
        // Nothing about this device's mac appears next to a `drop` action.
        for line in f.content.lines() {
            if line.contains("aa:bb:cc:00:11:22") {
                assert!(!line.contains("drop"), "an onboarding device's own mac must never appear on a drop line: {line}");
            }
        }
    }

    /// THE attack-still-caught proof: OnboardingGrace changes NOTHING about lan_only/internet_only/
    /// isolated enforcement for devices that ARE classified or explicitly blocked — those drop
    /// rules are untouched by this fix.
    #[test]
    fn onboarding_grace_does_not_weaken_enforcement_for_classified_or_blocked_devices() {
        let p = plan(vec![
            dev("cam", "00:0c:b5:00:00:02", NacPolicy::LanOnly),
            dev("bad", "ba:d0:00:00:00:04", NacPolicy::Isolated),
            dev("new-phone", "aa:bb:cc:00:11:22", NacPolicy::OnboardingGrace),
        ]);
        let f = render_nft(&p);
        assert!(f.content.contains("ether saddr @lan_only_macs oifname \"end0\" drop"), "lan_only still blocked from internet");
        assert!(f.content.contains("ether saddr @blocked_macs drop"), "isolated devices still fully blocked");
        assert!(f.content.contains("add element inet hookprobe_nac blocked_macs { ba:d0:00:00:00:04 }"));
    }

