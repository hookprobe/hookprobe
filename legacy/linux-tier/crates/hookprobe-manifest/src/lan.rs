//! LAN reconciler — the edge's **router** function (the missing keystone for the SASE AP).
//!
//! The WAN side (`multi_wan`), the radios (`wifi_cfg`) and L2/segmentation (`fabric`) already
//! exist; this brings the **AP/LAN bridge online as a gateway**: an IPv4 subnet + DHCP server for
//! clients, **NAT/masquerade out the WAN**, and dual-stack **IPv6** (claim the delegated /64,
//! RA/SLAAC, RA-Guard). It turns the edge from a sensor into a real router serving its trusted
//! Wi-Fi bubble — "the built-in Wi-Fi + routing" of the SASE edge.
//!
//! Output is generated networkd + nft artifacts under the staging dir; `network-apply.sh`
//! installs them. Intent-driven (subnet/WAN/DHCP/v6/RA-Guard are all declared, never hand-set).

use crate::multi_wan::{render_ra_guard_netdev, render_ra_guard_nft, render_ra_guard_ovs, GeneratedFile};

const BANNER: &str = "# GENERATED by hookprobe LAN reconciler from the signed manifest.\n# Do NOT edit — changes are overwritten. Declare intent instead (lan-intent.yaml).\n";

/// 2026-07-07 LLMNR/mDNS hardening fix (see `multi_wan.rs`'s identical constant/comment): a
/// `.network` file's own `LLMNR=`/`MulticastDNS=` keys default to `yes`/`no` per link when unset,
/// and that per-link setting always wins over `resolved.conf.d`'s global `-LLMNR` for that link.
/// The LAN gateway `.network` unit below is exactly such a file, so it must set both explicitly —
/// otherwise the trusted LAN bubble itself stays a live LLMNR responder despite the global
/// hardening drop-in.
const LLMNR_OFF: &str = "LLMNR=no\nMulticastDNS=no\n";

/// Operator intent for the LAN/AP gateway. Defaults serve a trusted Wi-Fi bubble with NAT + DHCP
/// + dual-stack IPv6 + RA-Guard — the portable-edge default.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(default)]
pub struct LanIntent {
    pub bridge: String,            // LAN bridge the AP radios attach to (e.g. "hp-br0")
    pub subnet_v4: String,         // CIDR, e.g. "10.66.0.0/24" → gateway .1, DHCP pool .10–.250
    pub wan: String,               // (default) WAN uplink to masquerade out, e.g. "end0"
    pub dhcp: bool,                // run a DHCP server for clients
    pub ipv6: bool,                // dual-stack: claim the delegated /64 + RA/SLAAC
    pub ra_guard: bool,            // observe (D16: log+accept by default) rogue RAs on the LAN
    pub ra_guard_hubs: Vec<String>,// known HomeKit-hub/router MACs allowed to send RAs outright (Thread RIO)
    /// D16 fix (2026-07-07 enforcement-separation audit): MACs actually CONFIRMED hostile RA/
    /// redirect sources — the ONLY sources RA-Guard hard-drops. Defaults empty: a fresh device
    /// with no confirmed-rogue history observes (logs) every non-allowlisted RA rather than
    /// silently severing a legitimate, not-yet-classified downstream router/HomeKit hub on first
    /// sight. Populate from a future stateful RA-source detector or admin action, never by default.
    pub ra_guard_confirmed_rogue: Vec<String>,
    pub ovs: bool,                 // LAN runs on an OVS bridge → RA-Guard via OpenFlow (else nft)
    /// 2026-07 on-metal audit fix: is `bridge` a GENUINE L2 bridge/switch port (Linux `bridge` or
    /// OVS), or a ROUTED L3 interface (an AP radio the reconciler put the gateway directly on —
    /// `brcmfmac` and similar onboard chips can't join a bridge; see `fabric::is_bridgeable`)?
    /// `bridge`-family nft hooks (used by `ovs=false` RA-Guard) only fire for frames actually
    /// traversing a bridge device — on a routed interface they load, pass `nft -c`, and never
    /// match a single packet (a silent RA-guard bypass). RA-Guard picks its nft family from this
    /// flag: `true` → bridge family (`render_ra_guard_nft`); `false` → netdev family attached to
    /// the interface's own ingress hook (`render_ra_guard_netdev`). Irrelevant when `ovs` is true
    /// (OVS is always genuinely bridged). Defaults to `true` — preserves prior behavior for
    /// callers that don't yet distinguish the two planes.
    pub bridged: bool,
}
impl Default for LanIntent {
    fn default() -> Self {
        LanIntent {
            bridge: "hp-br0".into(), subnet_v4: "10.66.0.0/24".into(), wan: "end0".into(),
            dhcp: true, ipv6: true, ra_guard: true, ra_guard_hubs: Vec::new(),
            ra_guard_confirmed_rogue: Vec::new(), ovs: true,
            bridged: true,
        }
    }
}
impl LanIntent {
    pub fn parse(yaml: &str) -> anyhow::Result<LanIntent> { Ok(serde_yaml::from_str(yaml)?) }
}

/// The resolved LAN plan: the gateway address, a one-line summary, and the artifacts to apply.
pub struct LanPlan {
    pub gateway_v4: String,
    pub artifacts: Vec<GeneratedFile>,
    pub summary: String,
}

/// `10.66.0.0/24` → ("10.66.0.1", 24). The gateway is the first host (.1) of the subnet.
fn gateway_and_prefix(cidr: &str) -> (String, u8) {
    let (net, plen) = cidr.split_once('/').unwrap_or((cidr, "24"));
    let prefix: u8 = plen.parse().unwrap_or(24);
    let mut octs: Vec<&str> = net.split('.').collect();
    while octs.len() < 4 { octs.push("0"); }
    let gw = format!("{}.{}.{}.1", octs[0], octs[1], octs[2]); // .1 host
    (gw, prefix)
}

/// Build the LAN gateway plan from intent.
pub fn plan(intent: &LanIntent) -> LanPlan {
    let (gw, prefix) = gateway_and_prefix(&intent.subnet_v4);
    let mut artifacts = Vec::new();
    let (ula_net, ula_gw) = lan_ula(1);   // stable ULA for this LAN segment (subnet_id 1)

    // 1. The LAN interface unit — ONE .network per interface. systemd-networkd applies only the
    //    FIRST-matching .network file for a link, so the v4 and v6 config MUST live in the same file;
    //    a separate `55-*-lan6.network` matching the same Name= is silently ignored (this was a real
    //    bug — LAN clients got no IPv6 at all). Dual-stack here: v4 gateway + DHCP server, and (when
    //    ipv6) a ULA gateway whose /64 is advertised via RA so clients SLAAC IPv6 with NO upstream PD;
    //    the WAN's delegated /64 is ALSO advertised (DHCPPrefixDelegation) for routed GUA when the ISP
    //    delegates one. ConfigureWithoutCarrier so the bridge is up before any client/AP associates.
    // BUG-N1 (2026-07-17, found on live CM5 metal): `RequiredForOnline=` is a **[Link]**-section
    // key (systemd.network(5)); emitting it under [Network] made networkd log
    // `Unknown key 'RequiredForOnline' in section [Network], ignoring` and SILENTLY DROP it — so the
    // whole intent documented below never took effect on real hardware. The AP radio stayed
    // "required for online", `systemd-networkd-wait-online` blocked on `wlan0: configuring`
    // (it never reaches routable — it's an AP, and its DHCPv6-PD uplink may never delegate), timed
    // out and FAILED → `network-online.target` never activated → every boot came up `degraded` and
    // anything ordered `After=network-online.target` (notably
    // `hookprobe-regdomain-reresolve.service`) never fired — which is exactly the
    // "regdomain stays cc=00" symptom seen in the field. The old unit tests only asserted
    // `content.contains("RequiredForOnline=no")`, which passes from ANY section, so they never
    // caught it; they now assert the KEY IS IN [Link] (see `required_for_online_is_in_link_section`).
    let mut net = format!(
        "{BANNER}# LAN on {br}: dual-stack gateway {gw}/{prefix}{v6a} + DHCP/RA, NAT'd to {wan}.\n\
         [Match]\nName={br}\n\n[Link]\nRequiredForOnline=no\n\n[Network]\n{LLMNR_OFF}Address={gw}/{prefix}\n",
        br = intent.bridge, wan = intent.wan,
        v6a = if intent.ipv6 { format!(" + {ula_gw}/64") } else { String::new() },
    );
    if intent.ipv6 { net.push_str(&format!("Address={ula_gw}/64\n")); }
    net.push_str("ConfigureWithoutCarrier=yes\n");
    // ADR 0034 D11/D14 (W1/W4): this unit is ALWAYS the AP/LAN-GATEWAY side (the client-facing
    // subnet this function renders — never the routable WAN uplink; that side is `multi_wan`'s
    // OWN `.network` unit, which carries `RequiredForOnline=routable`). Without this,
    // `systemd-networkd-wait-online` blocks `network-online.target` on the AP radio ("wlan0
    // configuring") — which in turn blocks `hookprobe-regdomain-reresolve.service` (ordered
    // `After=network-online.target`) from ever firing on a box whose WAN comes up cleanly but
    // whose AP radio legitimately never reaches routable "online" state. Safe for every LAN
    // topology this renderer serves (bridged OVS/Linux-bridge and routed-AP alike — see
    // `LanIntent::bridged`): it is scoped to THIS function's output (the downstream gateway),
    // never the upstream WAN `.network` unit multi_wan.rs renders separately.
    // (BUG-N1: the key itself now lives in the [Link] section emitted above — NOT here in
    // [Network], where systemd silently ignored it.)
    if intent.dhcp { net.push_str("DHCPServer=yes\n"); }
    // DHCPPrefixDelegation claims the WAN's delegated /64 (routed GUA when the upstream does DHCPv6-PD);
    // IPv6SendRA makes the edge the LAN router. Both are [Network] keys so they sit with the addresses.
    if intent.ipv6 { net.push_str("DHCPPrefixDelegation=yes\nIPv6SendRA=yes\n"); }
    if intent.dhcp {
        net.push_str("\n[DHCPServer]\nPoolOffset=10\nPoolSize=240\nEmitDNS=yes\nDNS=_server_address\n");
    }
    if intent.ipv6 {
        net.push_str(&format!(
            "\n[DHCPPrefixDelegation]\nUplinkInterface={wan}\nSubnetId=1\n\
             \n[IPv6SendRA]\nManaged=no\nOtherInformation=no\nEmitDNS=yes\n\
             \n[IPv6Prefix]\n# always-on ULA (masqueraded to the WAN GUA — works with no upstream PD)\nPrefix={ula_net}\n",
            wan = intent.wan,
        ));
    }
    artifacts.push(GeneratedFile { path: format!("50-hookprobe-lan-{}.network", intent.bridge), content: net });

    // 2. NAT — masquerade the LAN out the WAN: v4 subnet always, v6 ULA when dual-stack. + forwarding.
    artifacts.push(render_nat(&intent.bridge, &intent.wan, &intent.subnet_v4,
        if intent.ipv6 { Some(&ula_net) } else { None }));

    // 4. RA-Guard — only the edge (+ allowlisted HomeKit hubs) may emit RAs. Family is picked by
    // topology, never hardcoded: OVS is always genuinely bridged (OpenFlow); a plain nft plane
    // must additionally know whether `bridge` is a REAL bridge (bridge-family hooks fire) or a
    // routed L3 interface / AP radio (bridge-family hooks never fire there — netdev instead).
    if intent.ra_guard {
        artifacts.push(if intent.ovs {
            render_ra_guard_ovs(&intent.bridge, &intent.ra_guard_hubs, &intent.ra_guard_confirmed_rogue)
        } else if intent.bridged {
            render_ra_guard_nft(&intent.bridge, &intent.ra_guard_hubs, &intent.ra_guard_confirmed_rogue)
        } else {
            render_ra_guard_netdev(&intent.bridge, &intent.ra_guard_hubs, &intent.ra_guard_confirmed_rogue)
        });
    }

    // 5. Edge DNS — DHCP hands out the gateway itself as the resolver (`DNS=_server_address`), but
    //    systemd-resolved's stub only binds 127.0.0.53. Add a drop-in so it ALSO listens on the
    //    gateway IP, or LAN clients can't resolve. Emitted only when we're actually serving DHCP.
    if intent.dhcp {
        artifacts.push(GeneratedFile {
            path: format!("resolved/50-hookprobe-lan-dns-{}.conf", intent.bridge),
            content: format!(
                "{BANNER}# Edge DNS: resolved also listens on the LAN gateway(s) so DHCP/RA clients resolve.\n\
                 [Resolve]\nDNSStubListenerExtra={gw}\n{v6}",
                v6 = if intent.ipv6 { format!("DNSStubListenerExtra={ula_gw}\n") } else { String::new() },
            ),
        });
    }

    let summary = format!(
        "LAN {br} gw {gw}/{prefix}{dhcp} → NAT/{wan}{v6}{rg}",
        br = intent.bridge, dhcp = if intent.dhcp { " + DHCP" } else { "" },
        wan = intent.wan, v6 = if intent.ipv6 { " · dual-stack v6" } else { "" },
        rg = if intent.ra_guard { " · RA-Guard" } else { "" },
    );
    LanPlan { gateway_v4: gw, artifacts, summary }
}

/// Stable ULA for a LAN segment: `fd00:6606:<subnet_id>::/64`, gateway `…::1`. `fd00::/8` is the
/// ULA space (RFC 4193); `6606` echoes the `10.66` v4 LAN so operators can eyeball the pairing.
/// Deterministic (the reconciler is pure) and per-segment unique via `subnet_id`; it's masqueraded
/// (NAT66), so global uniqueness is moot. This is what lets LAN clients SLAAC IPv6 with no upstream PD.
fn lan_ula(subnet_id: u32) -> (String, String) {
    (format!("fd00:6606:{subnet_id}::/64"), format!("fd00:6606:{subnet_id}::1"))
}

/// NAT: masquerade the LAN out the WAN + enable forwarding. nft inet table so it composes with the
/// VRF/microseg tables; forwarding is set via a sysctl drop-in the apply ships. v4 subnet always;
/// `ula_v6` (when dual-stack) adds NAT66 so clients reach the IPv6 internet through the WAN's GUA
/// even when the upstream delegates NO prefix — the SASE edge stays online behind any uplink.
fn render_nat(bridge: &str, wan: &str, subnet_v4: &str, ula_v6: Option<&str>) -> GeneratedFile {
    let mut content = format!(
        "{BANNER}# NAT: masquerade the LAN (on {bridge}) out {wan}; enable IP forwarding.\n\
         sysctl -w net.ipv4.ip_forward=1 >/dev/null 2>&1 || true\n\
         sysctl -w net.ipv6.conf.all.forwarding=1 >/dev/null 2>&1 || true\n\
         nft add table inet hookprobe_nat 2>/dev/null || true\n\
         nft 'add chain inet hookprobe_nat postrouting {{ type nat hook postrouting priority 100; policy accept; }}' 2>/dev/null || true\n\
         nft add rule inet hookprobe_nat postrouting ip saddr {subnet_v4} oifname \"{wan}\" masquerade\n"
    );
    if let Some(ula) = ula_v6 {
        // NAT66: ULA can't be globally routed, so masquerade it to the WAN's GUA. Pragmatic SASE
        // choice — the edge gives clients IPv6 internet without depending on the upstream doing PD.
        content.push_str(&format!(
            "nft add rule inet hookprobe_nat postrouting ip6 saddr {ula} oifname \"{wan}\" masquerade\n"
        ));
    }
    GeneratedFile { path: "fabric/65-nat.plan".to_string(), content }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gateway_is_first_host() {
        assert_eq!(gateway_and_prefix("10.66.0.0/24"), ("10.66.0.1".into(), 24));
        assert_eq!(gateway_and_prefix("192.168.50.0/24"), ("192.168.50.1".into(), 24));
    }

    #[test]
    fn default_lan_is_a_full_router() {
        let p = plan(&LanIntent::default());
        assert_eq!(p.gateway_v4, "10.66.0.1");
        let paths: Vec<&str> = p.artifacts.iter().map(|a| a.path.as_str()).collect();
        assert!(paths.iter().any(|p| p.contains("50-hookprobe-lan-hp-br0.network")), "gateway+DHCP unit");
        assert!(paths.iter().any(|p| p.contains("65-nat.plan")), "NAT");
        assert!(paths.iter().any(|p| p.contains("64-ra-guard")), "RA-Guard");
        // v6 config MUST be MERGED into the single LAN .network (a separate 55-*.network would be
        // silently ignored — systemd-networkd applies one .network per link). No standalone lan6 file.
        assert!(!paths.iter().any(|p| p.contains("lan6")), "v6 must be merged, not a separate file");
        let gwu = p.artifacts.iter().find(|a| a.path.contains("50-hookprobe-lan")).unwrap();
        // one file carries: v4 gateway + DHCP + v6 ULA gateway + RA + PD claim + advertised ULA prefix
        assert!(gwu.content.contains("Address=10.66.0.1/24") && gwu.content.contains("DHCPServer=yes"));
        assert!(gwu.content.contains("Address=fd00:6606:1::1/64"), "ULA gateway");
        assert!(gwu.content.contains("IPv6SendRA=yes") && gwu.content.contains("DHCPPrefixDelegation=yes"));
        assert!(gwu.content.contains("Prefix=fd00:6606:1::/64"), "advertised ULA prefix");
        // LLMNR/mDNS hardening fix: the LAN gateway .network unit must explicitly disable both —
        // systemd-networkd's own per-link LLMNR default (`yes`) otherwise overrides
        // resolved.conf.d's global `-LLMNR` for this link (the trusted LAN bubble itself).
        assert!(gwu.content.contains("LLMNR=no") && gwu.content.contains("MulticastDNS=no"), "got: {}", gwu.content);
        // ADR 0034 D11/D14 (W1): the AP/LAN-gateway .network must NOT gate network-online.target —
        // only the WAN uplink (multi_wan.rs, RequiredForOnline=routable) should be waited on.
        assert!(gwu.content.contains("RequiredForOnline=no"), "got: {}", gwu.content);
        // BUG-N1 (2026-07-17, live CM5): …and it must be in the **[Link]** section. Under
        // [Network] systemd logs `Unknown key 'RequiredForOnline' in section [Network], ignoring`
        // and DROPS it — which is exactly what shipped: wait-online blocked on `wlan0: configuring`,
        // failed, `network-online.target` never activated, boot came up `degraded`, and
        // `hookprobe-regdomain-reresolve.service` (After=network-online.target) never fired
        // (the "regdomain stuck at cc=00" field symptom). The `.contains()` assert above passes from
        // ANY section, which is why this shipped broken — assert the SECTION.
        assert!(
            gwu.content.contains("[Link]\nRequiredForOnline=no\n"),
            "RequiredForOnline must be in a [Link] section, not [Network] — got: {}", gwu.content
        );
    }

    #[test]
    fn nat_masquerades_subnet_out_wan() {
        // v4-only NAT
        let n = render_nat("hp-br0", "end0", "10.66.0.0/24", None);
        assert!(n.content.contains("ip saddr 10.66.0.0/24 oifname \"end0\" masquerade"));
        assert!(n.content.contains("net.ipv4.ip_forward=1"));
        assert!(!n.content.contains("ip6 saddr"), "no NAT66 when v4-only");
        // dual-stack adds NAT66 for the ULA
        let n6 = render_nat("hp-br0", "end0", "10.66.0.0/24", Some("fd00:6606:1::/64"));
        assert!(n6.content.contains("ip6 saddr fd00:6606:1::/64 oifname \"end0\" masquerade"), "NAT66");
    }

    #[test]
    fn ra_guard_backend_follows_ovs_flag() {
        let ovs = plan(&LanIntent { ovs: true, ..Default::default() });
        assert!(ovs.artifacts.iter().any(|a| a.path.ends_with(".of")), "OVS RA-Guard");
        // ovs=false + bridged=true (default) — a real Linux-bridge fallback, bridge-family nft.
        let novs = plan(&LanIntent { ovs: false, ..Default::default() });
        assert!(novs.artifacts.iter().any(|a| a.path.ends_with(".nft") && !a.path.ends_with(".netdev.nft")), "bridge-family nft RA-Guard");
    }

    /// 2026-07 on-metal audit fix: a ROUTED AP (`bridged: false`, e.g. the Pi's onboard AP radio
    /// carrying the gateway directly, never a bridge member) must get netdev-family RA-Guard, not
    /// the bridge-family rules that can never fire for routed traffic.
    #[test]
    fn routed_ap_gets_netdev_family_ra_guard_not_bridge() {
        let routed = plan(&LanIntent { bridge: "wlan0".into(), ovs: false, bridged: false, ..Default::default() });
        let rg = routed.artifacts.iter().find(|a| a.path.contains("64-ra-guard")).expect("RA-Guard artifact");
        assert!(rg.path.ends_with(".netdev.nft"), "routed AP must render the netdev-family file, got {}", rg.path);
        assert!(rg.content.contains("table netdev hookprobe_raguard"), "netdev family");
        assert!(!rg.content.contains("table bridge"), "must NOT emit inert bridge-family rules for a routed iface");
        assert!(rg.content.contains("hook ingress device \"wlan0\""));
    }

    /// A genuinely bridged LAN (`bridged: true`, the default) keeps using bridge-family rules.
    #[test]
    fn bridged_lan_keeps_bridge_family_ra_guard() {
        let bridged = plan(&LanIntent { ovs: false, bridged: true, ..Default::default() });
        let rg = bridged.artifacts.iter().find(|a| a.path.contains("64-ra-guard")).expect("RA-Guard artifact");
        assert!(rg.content.contains("table bridge hookprobe_raguard"));
        assert!(!rg.path.ends_with(".netdev.nft"));
    }
}
