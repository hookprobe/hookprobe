//! Resolver-facing artifacts: a standard DNS Response Policy Zone (BIND/Unbound/Knot Resolver)
//! plus a dnsmasq blocklist fallback.
//!
//! **Why two formats:** this device's actually-wired LAN resolver is `systemd-resolved`
//! (`crates/hookprobe-manifest/src/lan.rs`), which has NO RPZ / domain-blocklist support at all —
//! see the crate doc / the ADR for the honest gap. RPZ is the industry-standard mechanism
//! (BIND `response-policy`, Unbound `rpz:`, Knot Resolver `policy.rpz`) an operator who swaps in
//! a capable resolver can load directly; the dnsmasq artifact covers the common lightweight-edge
//! alternative. Both are generated from the SAME [`crate::SinkholeEntry`] list, so they can never
//! disagree with each other.
//!
//! Both renderers degrade to a syntactically valid, EMPTY artifact on an empty sinkhole set —
//! fail toward "blocks nothing," never toward a malformed file a real resolver might refuse to
//! load (or, worse, partially mis-load).

use crate::{SinkholeEntry, SinkholeSource};

/// The zone name this RPZ artifact declares itself as (informational; the resolver's own config
/// decides what zone name it's loaded under — this is just the header comment's self-description).
pub const RPZ_ZONE_NAME: &str = "rpz.hookprobe-sinkhole";

fn source_summary(entry: &SinkholeEntry) -> String {
    entry
        .sources
        .iter()
        .map(|s| match s {
            SinkholeSource::DnsxaiBlockInstant { score, .. } => format!("dnsxai(score={score:.2})"),
            SinkholeSource::HydraIoc { family, .. } => format!("hydra({family})"),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Render a standard RPZ zone. `CNAME .` is the RPZ "NXDOMAIN" policy action — deliberately
/// chosen over sinkholing to a walled-garden IP: an NXDOMAIN can never itself be probed or
/// fingerprinted by the blocked client, matching the safest recommended RPZ default. A wildcard
/// entry (`*.domain`) is emitted alongside the exact domain so subdomains of a sinkholed domain
/// are ALSO refused (malware C2 infrastructure routinely round-robins across subdomains) — this
/// gives the RPZ artifact the SAME blocking scope `render_dnsmasq_conf` gets natively from
/// dnsmasq's own subdomain-inclusive `address=/domain/` semantics.
///
/// `serial` should be a monotonically increasing value (e.g. unix seconds) so a resolver that
/// tracks zone serials (AXFR-style reload semantics) notices the update; this function doesn't
/// enforce monotonicity itself — the caller owns that (same "pure function, caller owns time"
/// discipline every other renderer in this workspace holds to).
pub fn render_rpz(entries: &[SinkholeEntry], serial: u64) -> String {
    let mut z = format!(
        "; GENERATED by hookprobe-dns-sinkhole (roadmap A1) — do NOT hand-edit.\n\
         ; source: dnsxai BLOCK_INSTANT verdicts + HYDRA bundled domain IOCs (ADR 0027).\n\
         ; policy action: CNAME . (RPZ NXDOMAIN) — refuses the NAME, never touches the packet path.\n\
         $TTL 60\n\
         @ IN SOA localhost. root.localhost. ( {serial} 3600 900 604800 60 )\n\
         @ IN NS localhost.\n\
         ; {n} sinkholed domain(s)\n",
        n = entries.len(),
    );
    for e in entries {
        z.push_str(&format!("; {}: {}\n", e.domain, source_summary(e)));
        z.push_str(&format!("{d} CNAME .\n*.{d} CNAME .\n", d = e.domain));
    }
    z
}

/// Render a dnsmasq drop-in. `address=/domain/` with no IP argument returns NXDOMAIN on dnsmasq
/// 2.86 or newer, for the domain AND every subdomain of it — no separate wildcard line needed
/// here, unlike RPZ's own `*.domain` requirement above. Intended to be dropped into
/// `/etc/dnsmasq.d/` on a device that runs dnsmasq as its resolver (not this device's default —
/// see the module doc).
pub fn render_dnsmasq_conf(entries: &[SinkholeEntry]) -> String {
    let mut c = format!(
        "# GENERATED by hookprobe-dns-sinkhole (roadmap A1) — do NOT hand-edit.\n\
         # {n} sinkholed domain(s); source: dnsxai BLOCK_INSTANT verdicts + HYDRA bundled domain IOCs.\n\
         # address=/domain/ with no target IP = NXDOMAIN (dnsmasq >= 2.86); covers all subdomains.\n",
        n = entries.len(),
    );
    for e in entries {
        c.push_str(&format!("# {}: {}\naddress=/{}/\n", e.domain, source_summary(e), e.domain));
    }
    c
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::SinkholeSource;

    fn dnsxai_entry(domain: &str) -> SinkholeEntry {
        SinkholeEntry {
            domain: domain.to_string(),
            sources: vec![SinkholeSource::DnsxaiBlockInstant {
                score: 0.83,
                reasons: vec!["high_entropy:4.10".to_string()],
                src_ip: None,
            }],
        }
    }

    #[test]
    fn empty_entries_renders_a_syntactically_valid_empty_rpz_zone() {
        let z = render_rpz(&[], 1);
        assert!(z.contains("$TTL"));
        assert!(z.contains("SOA"));
        assert!(z.contains("0 sinkholed domain(s)"));
        // The header comment mentions the CNAME policy action for documentation purposes; what
        // matters is that no actual RECORD line (a bare domain followed by CNAME) is emitted.
        assert!(
            !z.lines().any(|l| !l.starts_with(';') && l.contains("CNAME")),
            "no CNAME record lines when nothing is sinkholed: {z}"
        );
    }

    #[test]
    fn empty_entries_renders_a_valid_empty_dnsmasq_conf() {
        let c = render_dnsmasq_conf(&[]);
        assert!(c.starts_with('#'), "still a well-formed comment-only file, never garbage");
        // The header comment documents the `address=/domain/` directive shape; what matters is
        // that no actual directive LINE (one starting with `address=`) is emitted.
        assert!(
            !c.lines().any(|l| l.starts_with("address=")),
            "no address= directives when nothing is sinkholed: {c}"
        );
    }

    #[test]
    fn rpz_zone_emits_exact_domain_and_wildcard_subdomain_as_nxdomain_cname() {
        let z = render_rpz(&[dnsxai_entry("evil.example")], 42);
        assert!(z.contains("evil.example CNAME .\n"));
        assert!(z.contains("*.evil.example CNAME .\n"), "subdomains must also be refused");
        assert!(z.contains("42"), "serial present");
        assert!(z.contains("dnsxai(score=0.83)"), "source attribution in a comment, never hidden");
    }

    #[test]
    fn dnsmasq_conf_emits_bare_address_directive_which_covers_subdomains_natively() {
        let c = render_dnsmasq_conf(&[dnsxai_entry("evil.example")]);
        assert!(c.contains("address=/evil.example/\n"));
        assert!(!c.contains("address=/evil.example/0.0.0.0"), "must be a bare NXDOMAIN directive, not an IP sinkhole");
    }

    #[test]
    fn multiple_entries_each_get_their_own_block_in_both_formats() {
        let entries = vec![dnsxai_entry("a.example"), dnsxai_entry("b.example")];
        let z = render_rpz(&entries, 1);
        let c = render_dnsmasq_conf(&entries);
        assert!(z.contains("a.example CNAME .") && z.contains("b.example CNAME ."));
        assert!(c.contains("address=/a.example/") && c.contains("address=/b.example/"));
        assert!(z.contains("2 sinkholed domain(s)"));
    }
}
