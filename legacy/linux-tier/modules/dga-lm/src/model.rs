//! Int8 char-level CNN forward pass — embedding -> conv1d -> ReLU -> global-max-pool ->
//! dense -> 2 logits (benign, dga). The hot loop (per-position conv dot product) goes
//! through `dot::dot_i8`, whose compiled kernel varies per build tier (see `dot.rs`).
//!
//! ## Weight blob layout (little-endian)
//!
//! ```text
//! offset  size                field
//! 0       4                   magic b"DGA1"
//! 4       1                   format version (1)
//! 5       1                   vocab size (must equal tokenizer::VOCAB)
//! 6       1                   embed_dim (16)
//! 7       1                   max_len (must equal tokenizer::MAX_LEN)
//! 8       1                   kernel size (4)
//! 9       1                   conv_out channels (32)
//! 10      2                   reserved/pad (0)
//! 12      VOCAB*EMBED_DIM     embedding table, i8, row-major [vocab][embed_dim]
//! +       CONV_OUT*WINDOW_LEN conv weights, i8, [out_channel][kernel*embed_dim]
//! +       CONV_OUT*4          conv bias, i32 LE, [out_channel]
//! +       CONV_OUT*2          dense weights, i8, [out_channel][2 logits]
//! +       2*4                 dense bias, i32 LE, [2 logits]
//! ```
//!
//! This is the SEED/BASELINE model (`../model/dga_seed.bin`, generated by
//! `../ci/quantize.py`) — see `../model/MODEL_CARD.md`: real weights are trained
//! OFF-DEVICE per ADR 0014; this is a small, hand-derived, honestly-labeled heuristic
//! placeholder that exercises the full int8 compute + dot-kernel path end-to-end, not a
//! validated DGA detector.

use crate::dot::dot_i8;
use crate::tokenizer::{self, MAX_LEN, VOCAB};

pub const EMBED_DIM: usize = 16;
pub const KERNEL: usize = 4;
/// One conv window = KERNEL chars * EMBED_DIM = 64 int8 elements = 4x16-lane SIMD chunks
/// (both the simd128 and relaxed-dot kernels process 16 int8 lanes per instruction).
pub const WINDOW_LEN: usize = KERNEL * EMBED_DIM;
pub const CONV_OUT: usize = 32;
pub const POSITIONS: usize = MAX_LEN - KERNEL + 1;

const MAGIC: [u8; 4] = *b"DGA1";
const HEADER_LEN: usize = 12;
const EMBED_BYTES: usize = VOCAB * EMBED_DIM;
const CONV_W_BYTES: usize = CONV_OUT * WINDOW_LEN;
const CONV_B_BYTES: usize = CONV_OUT * 4;
const DENSE_W_BYTES: usize = CONV_OUT * 2;
const DENSE_B_BYTES: usize = 2 * 4;
/// Total blob size — also the model's on-disk/L2 footprint. Acceptance gate: <= 256 KB
/// (see base-tier-build-ticket.md Phase 4's A76 budget row). This seed model is a few
/// KB; the budget headroom is intentional (documented in the model card).
pub const BLOB_LEN: usize = HEADER_LEN + EMBED_BYTES + CONV_W_BYTES + CONV_B_BYTES + DENSE_W_BYTES + DENSE_B_BYTES;

/// The embedded seed model bytes (see `../model/dga_seed.bin` + `../model/MODEL_CARD.md`).
pub static SEED_MODEL_BYTES: &[u8] = include_bytes!("../model/dga_seed.bin");

/// Borrowed view over a parsed weight blob, used internally by `forward()`. Never
/// copies at forward-pass time — all slices point straight into the `OwnedWeights` that
/// owns them.
struct Weights<'a> {
    embedding: &'a [i8],  // [VOCAB][EMBED_DIM]
    conv_w: &'a [i8],     // [CONV_OUT][WINDOW_LEN]
    conv_b: [i32; CONV_OUT],
    dense_w: &'a [i8],    // [CONV_OUT][2]
    dense_b: [i32; 2],
}

#[derive(Debug, PartialEq, Eq)]
pub enum ParseError {
    TooShort,
    BadMagic,
    BadVersion(u8),
    ShapeMismatch { field: &'static str, expected: u8, got: u8 },
}

/// Owned copy of a parsed weight blob (no `unsafe`/transmute — see `OwnedWeights::parse`).
pub struct OwnedWeights {
    embedding: Vec<i8>,
    conv_w: Vec<i8>,
    conv_b: [i32; CONV_OUT],
    dense_w: Vec<i8>,
    dense_b: [i32; 2],
}

impl OwnedWeights {
    /// Parse a weight blob (`SEED_MODEL_BYTES` in production) into owned storage.
    /// Fully safe (no `unsafe`, no transmute) — this crate is `#![forbid(unsafe_code)]`
    /// (see `lib.rs`), so the u8 -> i8 reinterpretation is an explicit per-byte cast
    /// rather than a pointer-cast transmute. Called once at startup, not per-tick.
    pub fn parse(blob: &[u8]) -> Result<OwnedWeights, ParseError> {
        if blob.len() < HEADER_LEN {
            return Err(ParseError::TooShort);
        }
        if blob[0..4] != MAGIC {
            return Err(ParseError::BadMagic);
        }
        let version = blob[4];
        if version != 1 {
            return Err(ParseError::BadVersion(version));
        }
        let vocab = blob[5];
        if vocab as usize != VOCAB {
            return Err(ParseError::ShapeMismatch { field: "vocab", expected: VOCAB as u8, got: vocab });
        }
        let embed_dim = blob[6];
        if embed_dim as usize != EMBED_DIM {
            return Err(ParseError::ShapeMismatch { field: "embed_dim", expected: EMBED_DIM as u8, got: embed_dim });
        }
        let max_len = blob[7];
        if max_len as usize != MAX_LEN {
            return Err(ParseError::ShapeMismatch { field: "max_len", expected: MAX_LEN as u8, got: max_len });
        }
        let kernel = blob[8];
        if kernel as usize != KERNEL {
            return Err(ParseError::ShapeMismatch { field: "kernel", expected: KERNEL as u8, got: kernel });
        }
        let conv_out = blob[9];
        if conv_out as usize != CONV_OUT {
            return Err(ParseError::ShapeMismatch { field: "conv_out", expected: CONV_OUT as u8, got: conv_out });
        }
        if blob.len() < BLOB_LEN {
            return Err(ParseError::TooShort);
        }

        let mut off = HEADER_LEN;
        let embedding: Vec<i8> = blob[off..off + EMBED_BYTES].iter().map(|&b| b as i8).collect();
        off += EMBED_BYTES;
        let conv_w: Vec<i8> = blob[off..off + CONV_W_BYTES].iter().map(|&b| b as i8).collect();
        off += CONV_W_BYTES;
        let mut conv_b = [0i32; CONV_OUT];
        for (i, chunk) in blob[off..off + CONV_B_BYTES].chunks_exact(4).enumerate() {
            conv_b[i] = i32::from_le_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]);
        }
        off += CONV_B_BYTES;
        let dense_w: Vec<i8> = blob[off..off + DENSE_W_BYTES].iter().map(|&b| b as i8).collect();
        off += DENSE_W_BYTES;
        let mut dense_b = [0i32; 2];
        for (i, chunk) in blob[off..off + DENSE_B_BYTES].chunks_exact(4).enumerate() {
            dense_b[i] = i32::from_le_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]);
        }

        Ok(OwnedWeights { embedding, conv_w, conv_b, dense_w, dense_b })
    }

    fn as_view(&self) -> Weights<'_> {
        Weights {
            embedding: &self.embedding,
            conv_w: &self.conv_w,
            conv_b: self.conv_b,
            dense_w: &self.dense_w,
            dense_b: self.dense_b,
        }
    }

    /// Forward pass: tokenize `domain`, run embedding -> conv -> ReLU -> global-max-pool
    /// -> dense, return raw `[benign_logit, dga_logit]` (i32, pre-softmax).
    pub fn forward(&self, domain: &str) -> [i32; 2] {
        let w = self.as_view();
        let ids = tokenizer::tokenize(domain);

        // Embedding lookup: MAX_LEN rows of EMBED_DIM i8 each.
        let mut embedded = [0i8; MAX_LEN * EMBED_DIM];
        for (pos, &id) in ids.iter().enumerate() {
            let row = &w.embedding[(id as usize) * EMBED_DIM..(id as usize + 1) * EMBED_DIM];
            embedded[pos * EMBED_DIM..(pos + 1) * EMBED_DIM].copy_from_slice(row);
        }

        // Conv1d + ReLU + global max-pool, one output channel at a time.
        let mut pooled = [0i32; CONV_OUT];
        let mut window = [0i8; WINDOW_LEN];
        for (oc, slot) in pooled.iter_mut().enumerate() {
            let kw = &w.conv_w[oc * WINDOW_LEN..(oc + 1) * WINDOW_LEN];
            let mut max_val = i32::MIN;
            for p in 0..POSITIONS {
                window.copy_from_slice(&embedded[p * EMBED_DIM..p * EMBED_DIM + WINDOW_LEN]);
                let dot = dot_i8(&window, kw);
                let activated = (dot + w.conv_b[oc]).max(0); // ReLU
                if activated > max_val {
                    max_val = activated;
                }
            }
            *slot = max_val;
        }

        // Requantize pooled i32 -> i8 (fixed right-shift; MUST match
        // `ci/quantize.py::REQUANT_SHIFT`, the single source of truth for the seed
        // model's activation scale — a mismatch here silently zeroes out the seed's
        // signal, see the git history of this constant) before the dense layer, so the
        // dense layer's weights stay int8 too (keeps the whole model int8, per the
        // ticket's "int8 char-level" requirement end to end, not just the conv layer).
        const REQUANT_SHIFT: u32 = 2;
        let mut pooled_i8 = [0i8; CONV_OUT];
        for (dst, &src) in pooled_i8.iter_mut().zip(pooled.iter()) {
            *dst = (src >> REQUANT_SHIFT).clamp(0, 127) as i8;
        }

        // Dense: [CONV_OUT] -> [2 logits].
        let mut logits = w.dense_b;
        for (i, &pi8) in pooled_i8.iter().enumerate() {
            logits[0] += pi8 as i32 * w.dense_w[i * 2] as i32;
            logits[1] += pi8 as i32 * w.dense_w[i * 2 + 1] as i32;
        }
        logits
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn seed() -> OwnedWeights {
        OwnedWeights::parse(SEED_MODEL_BYTES).expect("seed model must parse")
    }

    #[test]
    fn seed_model_is_within_size_budget() {
        // Acceptance gate: model <= 256 KB (L2-resident).
        assert!(SEED_MODEL_BYTES.len() <= 256 * 1024, "seed model is {} bytes, budget is 256 KiB", SEED_MODEL_BYTES.len());
        assert_eq!(SEED_MODEL_BYTES.len(), BLOB_LEN);
    }

    #[test]
    fn seed_model_parses_cleanly() {
        let _ = seed();
    }

    #[test]
    fn forward_is_deterministic() {
        let w = seed();
        let a = w.forward("example.com");
        let b = w.forward("example.com");
        assert_eq!(a, b);
    }

    #[test]
    fn empty_domain_does_not_panic() {
        let w = seed();
        let _ = w.forward("");
    }

    #[test]
    fn max_length_domain_does_not_panic() {
        let w = seed();
        let long = "a".repeat(200);
        let _ = w.forward(&long);
    }
}
